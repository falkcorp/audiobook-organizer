const (
	dashboardsGlob = repoRoot + "/deploy/grafana/dashboards/*.json"
	rulesGlob      = repoRoot + "/deploy/prometheus/*.yml"
)

// foreignSeries are referenced series another exporter serves, never this
// binary: the disk alert reads node_exporter's filesystem gauges. Each entry
// must still be referenced (a stale entry fails), so the list cannot grow
// into a way to silence the test.
var foreignSeries = map[string]string{
	"node_filesystem_avail_bytes": "node_exporter",
	"node_filesystem_size_bytes":  "node_exporter",
}

// syntheticSeries are generated by Prometheus itself for every target.
var syntheticSeries = map[string]bool{"up": true}

// reference is one series name and where it was read.
type reference struct{ name, where string }

func TestDeployReferencedSeriesServed(t *testing.T) {
	refs, recorded := deployReferences(t)
	if len(refs) == 0 {
		t.Fatal("no series referenced under deploy/: the extractor is reading nothing")
	}
	served := servedSeries(t)
	usedForeign := map[string]bool{}
	var missing []string
	for _, r := range refs {
		switch {
		case served[r.name], syntheticSeries[r.name], recorded[r.name]:
		case foreignSeries[r.name] != "":
			usedForeign[r.name] = true
		default:
			missing = append(missing, fmt.Sprintf("%s (%s)", r.name, r.where))
		}
	}
	slices.Sort(missing)
	for _, m := range slices.Compact(missing) {
		t.Errorf("referenced but not served by the seeded /metrics scrape: %s. A rename needs its dashboard and rule edits in the same PR (09 §9.2.7)", m)
	}
	for name, exporter := range foreignSeries {
		if !usedForeign[name] {
			t.Errorf("foreignSeries lists %s (%s), which nothing under deploy/ references any more: remove the entry", name, exporter)
		}
	}
	t.Logf("%d references to %d distinct series checked against %d served series", len(refs), len(distinct(refs)), len(served))
}

func distinct(refs []reference) map[string]bool {
	out := map[string]bool{}
	for _, r := range refs {
		out[r.name] = true
	}
	return out
}

// servedSeries is every sample name on one GET /metrics of the default
// registry (TestMain seeded it): family names plus _bucket/_sum/_count.
func servedSeries(t *testing.T) map[string]bool {
	t.Helper()
	rec := httptest.NewRecorder()
	promhttp.Handler().ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/metrics", nil))
	if rec.Code != http.StatusOK {
		t.Fatalf("/metrics returned %d", rec.Code)
	}
	out := map[string]bool{}
	for line := range strings.SplitSeq(rec.Body.String(), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		end := strings.IndexAny(line, "{ ")
		if end <= 0 {
			t.Fatalf("unparsable exposition line %q", line)
		}
		out[line[:end]] = true
	}
	return out
}

// deployReferences reads every PromQL expression under deploy/: each `expr`
// in the dashboards (any depth) and each `expr` and rule-test input `series`
// in the Prometheus rule files. It returns the series names they select and
// the names recording rules define (served when their inputs are).
func deployReferences(t *testing.T) ([]reference, map[string]bool) {
	t.Helper()
	var refs []reference
	recorded := map[string]bool{}
	dashboards, err := filepath.Glob(dashboardsGlob)
	if err != nil || len(dashboards) == 0 {
		t.Fatalf("no dashboards at %s: %v", dashboardsGlob, err)
	}
	for _, path := range dashboards {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		var doc any
		if err := json.Unmarshal(raw, &doc); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		walkStrings(doc, func(key, val string) {
			if key == "expr" {
				for _, n := range seriesNames(val) {
					refs = append(refs, reference{n, filepath.Base(path)})
				}
			}
		})
	}
	rules, err := filepath.Glob(rulesGlob)
	if err != nil || len(rules) == 0 {
		t.Fatalf("no rule files at %s: %v", rulesGlob, err)
	}
	for _, path := range rules {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		var doc any
		if err := yaml.Unmarshal(raw, &doc); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		walkStrings(doc, func(key, val string) {
			switch key {
			case "expr", "series":
				for _, n := range seriesNames(val) {
					refs = append(refs, reference{n, filepath.Base(path)})
				}
			case "record":
				recorded[strings.TrimSpace(val)] = true
			}
		})
	}
	return refs, recorded
}

// walkStrings calls fn for every string value held under a map key.
func walkStrings(v any, fn func(key, val string)) {
	switch x := v.(type) {
	case map[string]any:
		for k, val := range x {
			if s, ok := val.(string); ok {
				fn(k, s)
			} else {
				walkStrings(val, fn)
			}
		}
	case []any:
		for _, e := range x {
			walkStrings(e, fn)
		}
	}
}

var (
	// promqlStrings are quoted literals ("...", '...', `...`).
	promqlStrings = regexp.MustCompile("\"(?:[^\"\\\\]|\\\\.)*\"|'(?:[^'\\\\]|\\\\.)*'|`[^`]*`")
	// nameMatcher is a __name__ equality matcher inside braces.
	nameMatcher = regexp.MustCompile(`__name__\s*=\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')`)
	// labelLists are the label-name lists of grouping and matching clauses.
	labelLists = regexp.MustCompile(`\b(by|without|on|ignoring|group_left|group_right)\s*\([^)]*\)`)
	// promqlToken splits what is left into variables, numbers and durations
	// (anything glued to a leading digit: 1.1e10, 5m, 1h30m), identifiers and
	// single other characters.
	promqlToken = regexp.MustCompile(`\$\{?\w+\}?|[0-9][0-9A-Za-z_.]*|[A-Za-z_:][A-Za-z0-9_:]*|\S`)
)

// promqlKeywords are PromQL words that are not series names.
var promqlKeywords = map[string]bool{
	"and": true, "or": true, "unless": true, "bool": true, "offset": true,
	"by": true, "without": true, "on": true, "ignoring": true, "group_left": true, "group_right": true,
	"inf": true, "nan": true, "Inf": true, "NaN": true, "atan2": true,
}

// seriesNames returns the metric names a PromQL expression selects: each
// identifier that is not a function or aggregation (followed by "("), a
// keyword, a label name in a grouping clause or a matcher, a number, a
// duration or a Grafana variable, plus each __name__="x" matcher's value.
func seriesNames(expr string) []string {
	var names []string
	for _, m := range nameMatcher.FindAllStringSubmatch(expr, -1) {
		names = append(names, strings.Trim(m[1], `"'`))
	}
	s := promqlStrings.ReplaceAllString(expr, `""`)
	s = labelLists.ReplaceAllString(s, " ")
	s = stripBracketed(stripBracketed(s, '{', '}'), '[', ']')
	toks := promqlToken.FindAllString(s, -1)
	for i, tok := range toks {
		c := tok[0]
		if !(c == '_' || c == ':' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z') {
			continue // number, variable, operator, punctuation
		}
		if promqlKeywords[tok] || (i+1 < len(toks) && toks[i+1] == "(") {
			continue
		}
		names = append(names, tok)
	}
	sort.Strings(names)
	return slices.Compact(names)
}

// stripBracketed removes every open...close span (label matchers, range and
// subquery selectors), nesting-aware.
func stripBracketed(s string, open, close byte) string {
	var b strings.Builder
	depth := 0
	for i := 0; i < len(s); i++ {
		switch {
		case s[i] == open:
			depth++
		case s[i] == close && depth > 0:
			depth--
			b.WriteByte(' ')
		case depth == 0:
			b.WriteByte(s[i])
		}
	}
	return b.String()
}

// TestSeriesNames_Extractor pins the extractor on the shapes deploy/ uses, so
// a parser bug cannot pass the reference test by reading nothing.
func TestSeriesNames_Extractor(t *testing.T) {
	for expr, want := range map[string][]string{
		`sum by (task, outcome) (rate(ai_requests_total[5m]))`:                                                            {"ai_requests_total"},
		`histogram_quantile(0.95, sum by (le, view) (rate(batman_bucket{view="page"}[$__rate_interval])))`:                {"batman_bucket"},
		`sum(increase(robin_count[1h])) - sum(increase(robin_bucket{le="5"}[1h]))`:                                        {"robin_bucket", "robin_count"},
		`process_resident_memory_bytes{job="audiobook-organizer"} > 1.1e10`:                                               {"process_resident_memory_bytes"},
		`up{job="audiobook-organizer"} == 0`:                                                                              {"up"},
		`a_total / on(job) group_left(instance) b_total and c_total unless d offset 5m`:                                   {"a_total", "b_total", "c_total", "d"},
		`label_replace(sum by (def_id) (joker_total), "op_type", "$1", "def_id", "(.*)")`:                                 {"joker_total"},
		`{__name__="alfred_total", task="x"}`:                                                                             {"alfred_total"},
		`max by (def_id) (gordon_seconds) > clamp_min(max by (def_id) (gordon_timeout_seconds), 1800)`:                    {"gordon_seconds", "gordon_timeout_seconds"},
		`delta(selina_titles[$__range])`:                                                                                  {"selina_titles"},
		`rate(bane_total[5m:1m]) * 60`:                                                                                    {"bane_total"},
		`audiobook_organizer:ops_items_by_op_type:sum`:                                                                    {"audiobook_organizer:ops_items_by_op_type:sum"},
		`ai_failures_total{provider="local",model="m",task="embed",reason="unreachable"}`:                                 {"ai_failures_total"},
		`sum(rate(ai_tokens_total{task="batch_parse"}[1h])) / sum(rate(x_total{task="batch_parse",accepted="true"}[1h]))`: {"ai_tokens_total", "x_total"},
	} {
		if got := seriesNames(expr); !slices.Equal(got, want) {
			t.Errorf("seriesNames(%q) = %v, want %v", expr, got, want)
		}
	}
}
