// corpus is one store the suite runs on.
type corpus struct {
	name    string
	dir     string // a store directory: db/audiobooks.pebble, state/, import/, library/
	answers string // the answers directory the drill compares with ("" = none)
	// quarantineCases are the overlay's quarantined cases: the quarantine
	// report must be exactly these (09 §9.3).
	quarantineCases []r2Stage2Case
	// wrote is what the pre-freeze binary wrote (prefreeze-written only).
	wrote *prefreezeRows
	// linkTables: hard-link SSTs when copying (the generated shaped store
	// only; never the committed corpus, whose files a checkpoint would chmod).
	linkTables bool
}

func r0Corpus(t *testing.T) corpus {
	t.Helper()
	root := r2RepoRoot(t)
	m := loadR2Stage2Manifest(t)
	var q []r2Stage2Case
	for _, c := range m.Overlay {
		if c.Outcome == "quarantined" {
			q = append(q, c)
		}
	}
	require.NotEmpty(t, q, "the overlay has no quarantined case")
	return corpus{
		name:            "r0",
		dir:             filepath.Join(root, filepath.FromSlash(r2corpusDirRel), "overlay"),
		answers:         filepath.Join(root, filepath.FromSlash(r2corpusDirRel), "answers", "overlay"),
		quarantineCases: q,
	}
}

// inCI reports a CI run, where the prefreeze-written subtests are required.
func inCI() bool { return os.Getenv("CI") != "" }

// forEachCorpus runs fn as one subtest per corpus: r0, prefreeze-written, and
// shaped when R2_SHAPED_STORE is set.
func forEachCorpus(t *testing.T, fn func(t *testing.T, c corpus)) {
	t.Helper()
	t.Run("r0", func(t *testing.T) { fn(t, r0Corpus(t)) })
	t.Run("prefreeze-written", func(t *testing.T) {
		if os.Getenv(r2PrefreezeBinEnv) == "" {
			if inCI() {
				t.Fatalf("%s is not set: CI must fetch the pre-freeze binary (scripts/ci/fetch_prefreeze_binary.sh)", r2PrefreezeBinEnv)
			}
			t.Skipf("%s is not set: no pre-freeze binary to write the corpus with (CI fetches one)", r2PrefreezeBinEnv)
		}
		fn(t, prefreezeWrittenCorpus(t))
	})
	if src := os.Getenv(r2ShapedStoreEnv); src != "" {
		t.Run("shaped", func(t *testing.T) {
			fn(t, corpus{name: "shaped", dir: src, linkTables: true})
		})
	}
}

// copyCorpus copies a store directory into a new temporary directory and
// returns it: real copies, tables hard linked only when linkTables is set.
// copyShapedStore's rule for the generated store (its manifest left behind).
func copyCorpus(t *testing.T, c corpus) string {
	t.Helper()
	dst := t.TempDir()
	if c.linkTables {
		require.NoError(t, copyShapedStore(c.dir, dst))
		return dst
	}
	require.NoError(t, copyTree(c.dir, dst))
	return dst
}

// copyTree copies every regular file and directory of src into dst.
func copyTree(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		switch {
		case d.IsDir():
			return os.MkdirAll(target, 0o755)
		case d.Type().IsRegular():
			return copyShapedFile(path, target)
		}
		return nil
	})
}

