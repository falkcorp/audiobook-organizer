// familyDigest is one family's count and SHA-256 over its keys and values,
// in key order, of the keys no exclusion covers.
type familyDigest struct {
	Keys int64
	h    hash.Hash
}

func (d *familyDigest) add(k, v []byte) {
	if d.h == nil {
		d.h = sha256.New()
	}
	var n [8]byte
	for _, b := range [][]byte{k, v} {
		binary.LittleEndian.PutUint64(n[:], uint64(len(b)))
		_, _ = d.h.Write(n[:])
		_, _ = d.h.Write(b)
	}
	d.Keys++
}

func (d *familyDigest) digest() string {
	if d.h == nil {
		return ""
	}
	return hex.EncodeToString(d.h.Sum(nil))
}

// quarantineRecord is the part of a storage.QuarantineRecord (05-storage
// §5S.3.13, c/storage/quarantine/<step-id>/<n>) the suite reads, found by
// decoding every value under c/storage/ whose key names the quarantine.
type quarantineRecord struct {
	Key    []byte `json:"key"`
	Step   string `json:"step"`
	Reason string `json:"reason"`
}

// idKinds are 14 E2's ID families: every ID a key of one of these carries
// after its prefix is kept by the cutover. Integration-instance IDs live in
// the settings blob, not in a family; F3-06's config oracle checks them.
var idKinds = map[string]string{
	"u:":           "user",
	"role:":        "role",
	"apikey:":      "key",
	"oauthid:":     "oauth identity",
	"import_path:": "import root",
	"opv3:run:":    "run",
	"opv2:op:":     "run",
}

// storeScan is one pass over a store: per-family digests of every books key
// no exclusion covers, the count of keys each step's Source and each skipped
// list entry holds, the IDs of idKinds, the tokens of the core keys (where
// cutover steps import to), the quarantine records and the IDs they hold, and
// the bookkeeping rows (checked grow-only, bookkeepingProblems).
type storeScan struct {
	Total    int64
	Families map[string]*familyDigest
	// Plain is the "nothing moved" digest set, filled when the spec asks for
	// it: every books key but the bookkeeping rows, no step or list
	// exclusion. Same pass, so the store is read once.
	Plain       map[string]*familyDigest
	InSource    map[string]int64 // step ID -> keys inside its Source
	Skipped     map[string]int64 // list entry value -> keys
	IDs         map[string]map[string]bool
	Bookkeeping map[string][]byte
	// coreTokens are the tokens of every core key (split at anything but a
	// letter, digit, '-' or '_'): an ID that is one was imported, kept.
	coreTokens map[string]bool
	// quarantinedIDs are the last ':' segments of the quarantined keys.
	quarantinedIDs map[string]bool
	Quarantine     []quarantineRecord
	rows           map[string][]byte // every books key, small stores only
}

type scanSpec struct {
	steps    []cutoverStep
	shared   []sharedEntry
	keepRows bool
	// plain fills storeScan.Plain.
	plain bool
	// hashCore digests the core keys (c/, m/) as two more families: the
	// drill compares whole stores, the cutover checks only books ranges.
	hashCore bool
}

// classify names the books family of key (the longest registered prefix), ""
// for a core key (c/, m/).
type familyIndex struct{ prefixes []string }

func newFamilyIndex() familyIndex {
	var p []string
	for _, f := range database.KeyFamilies() {
		p = append(p, f.Prefix)
	}
	return familyIndex{prefixes: p}
}

func (fi familyIndex) family(key []byte) string {
	best := ""
	for _, p := range fi.prefixes {
		if len(p) > len(best) && bytes.HasPrefix(key, []byte(p)) {
			best = p
		}
	}
	if best == "" {
		return "(unregistered)"
	}
	return best
}

func coreFamily(f string) bool { return f == "c/" || f == "m/" }

// scanStore reads every key of the Pebble store at dir, read-only.
func scanStore(t *testing.T, dir string, spec scanSpec) *storeScan {
	t.Helper()
	db, err := pebble.Open(dir, &pebble.Options{ReadOnly: true})
	require.NoError(t, err, "open %s read-only", dir)
	defer func() { require.NoError(t, db.Close()) }()
	it, err := db.NewIter(nil)
	require.NoError(t, err)
	defer func() { require.NoError(t, it.Close()) }()
	s := newStoreScan(spec)
	fi := newFamilyIndex()
	for it.First(); it.Valid(); it.Next() {
		s.add(fi, spec, it.Key(), it.Value())
	}
	return s
}

// newStoreScan is an empty scan for spec, ready for add.
func newStoreScan(spec scanSpec) *storeScan {
	s := &storeScan{
		Families:       map[string]*familyDigest{},
		Plain:          map[string]*familyDigest{},
		InSource:       map[string]int64{},
		Skipped:        map[string]int64{},
		IDs:            map[string]map[string]bool{},
		Bookkeeping:    map[string][]byte{},
		coreTokens:     map[string]bool{},
		quarantinedIDs: map[string]bool{},
	}
	if spec.keepRows {
		s.rows = map[string][]byte{}
	}
	return s
}

func (s *storeScan) add(fi familyIndex, spec scanSpec, key, val []byte) {
	s.Total++
	fam := fi.family(key)
	if s.rows != nil {
		s.rows[string(key)] = slices.Clone(val)
	}
	if coreFamily(fam) {
		for _, tok := range keyTokens(key) {
			s.coreTokens[tok] = true
		}
		if bytes.HasPrefix(key, []byte("c/storage")) && bytes.Contains(key, []byte("quarantine")) {
			if q, ok := decodeQuarantine(val); ok {
				s.Quarantine = append(s.Quarantine, q)
				qk := string(q.Key)
				s.quarantinedIDs[qk[strings.LastIndexByte(qk, ':')+1:]] = true
			}
		}
		if spec.hashCore {
			s.digestOf(s.Families, fam).add(key, val)
		}
		return
	}
	if kind, ok := idKinds[fam]; ok {
		if s.IDs[kind] == nil {
			s.IDs[kind] = map[string]bool{}
		}
		s.IDs[kind][string(key[len(fam):])] = true
	}
	for _, e := range spec.shared {
		if e.Class == "bookkeeping" && e.covers(key) {
			s.Bookkeeping[string(key)] = slices.Clone(val)
			s.Skipped[e.Value]++
			return
		}
	}
	if spec.plain {
		s.digestOf(s.Plain, fam).add(key, val)
	}
	for _, st := range spec.steps {
		if st.inSource(key) {
			s.InSource[st.ID]++
			return
		}
	}
	for _, e := range spec.shared {
		if e.skipped() && e.covers(key) {
			s.Skipped[e.Value]++
			return
		}
	}
	s.digestOf(s.Families, fam).add(key, val)
}

// keyTokens splits a key at every byte that is not a letter, digit, '-' or
// '_' (ULIDs, UUIDs, seed role names and integer IDs stay whole).
func keyTokens(k []byte) []string {
	return strings.FieldsFunc(string(k), func(r rune) bool {
		return !(r >= '0' && r <= '9' || r >= 'A' && r <= 'Z' || r >= 'a' && r <= 'z' || r == '-' || r == '_')
	})
}

func (s *storeScan) digestOf(m map[string]*familyDigest, fam string) *familyDigest {
	d := m[fam]
	if d == nil {
		d = &familyDigest{}
		m[fam] = d
	}
	return d
}

// plainView is s with its Plain digests as its families, for byteProblems.
func (s *storeScan) plainView() *storeScan {
	return &storeScan{Families: s.Plain, rows: s.rows}
}

// decodeQuarantine decodes a quarantine record, with or without storage's
// codec envelope (a tag byte, then a JSON object carrying "v").
func decodeQuarantine(v []byte) (quarantineRecord, bool) {
	if i := bytes.IndexByte(v, '{'); i > 0 && i <= 4 {
		v = v[i:]
	}
	var q quarantineRecord
	if json.Unmarshal(v, &q) != nil || len(q.Key) == 0 || q.Step == "" {
		return q, false
	}
	return q, true
}

// ---------------------------------------------------------------- the checks

// countProblems: per step, 05-storage §5S.3.13 Verify's count rule, checked
// against an independent scan rather than the step's own numbers alone (rule
// 3): the report's read equals the keys the before-scan found in the Source,
// read = imported + quarantined + deleted, every Source range is empty after
// (Residual keys excepted), and the quarantine records naming the step are as
// many as its report says.
func countProblems(steps []cutoverStep, before, after *storeScan) []string {
	var out []string
	for _, st := range steps {
		r := st.Report
		if got := before.InSource[st.ID]; got != r.Read {
			out = append(out, fmt.Sprintf("%s: the report read %d rows, the Source held %d", st.ID, r.Read, got))
		}
		if sum := r.Imported + r.Quarantined + r.Deleted; sum != r.Read {
			out = append(out, fmt.Sprintf("%s: read %d != imported %d + quarantined %d + deleted %d", st.ID, r.Read, r.Imported, r.Quarantined, r.Deleted))
		}
		if left := after.InSource[st.ID]; left != 0 {
			out = append(out, fmt.Sprintf("%s: %d rows are left in its Source", st.ID, left))
		}
		var q int64
		for _, rec := range after.Quarantine {
			if rec.Step == st.ID {
				q++
			}
		}
		if q != r.Quarantined {
			out = append(out, fmt.Sprintf("%s: the report quarantined %d rows, the store holds %d quarantine records", st.ID, r.Quarantined, q))
		}
	}
	return out
}

// quarantineProblems: the quarantine report equals exactly the overlay's
// quarantine cases that fall in a registered step's Source (09 §9.3): every
// record names a key of one of those cases, and every entity row of such a
// case (a key of an idKinds family: a user, a role, a run, ...) has a record
// naming that entity (a run's opv2:op: and opv3:run: rows are one run, so a
// record of either covers it). A case's secondary rows (its idx: entries, a
// run's events) go with their entity and need no record of their own. A
// record no case accounts for is a row quarantined in error.
func quarantineProblems(steps []cutoverStep, cases []r2Stage2Case, recs []quarantineRecord) []string {
	var out []string
	inAnySource := func(k string) bool {
		for _, st := range steps {
			if st.inSource([]byte(k)) {
				return true
			}
		}
		return false
	}
	fi := newFamilyIndex()
	entity := func(k string) (string, bool) {
		fam := fi.family([]byte(k))
		kind, ok := idKinds[fam]
		return kind + " " + k[len(fam):], ok
	}
	owner := map[string]string{}
	want := map[string]string{} // entity -> case label
	for _, c := range cases {
		for _, k := range c.Keys {
			row, _, _ := strings.Cut(k, "#")
			if !inAnySource(row) {
				continue
			}
			owner[row] = c.Label
			if e, ok := entity(row); ok {
				want[e] = c.Label
			}
		}
	}
	got := map[string]bool{}
	labels := map[string]bool{}
	for _, r := range recs {
		label, ok := owner[string(r.Key)]
		if !ok {
			out = append(out, fmt.Sprintf("%s quarantined %q, which is no overlay quarantine case", r.Step, r.Key))
			continue
		}
		labels[label] = true
		if e, ok := entity(string(r.Key)); ok {
			got[e] = true
		}
	}
	for _, e := range sortedKeys(want) {
		if !got[e] {
			out = append(out, fmt.Sprintf("overlay case %s: %s should be quarantined and is not", want[e], e))
		}
	}
	for _, row := range sortedKeys(owner) {
		if l := owner[row]; !labels[l] {
			out = append(out, fmt.Sprintf("overlay case %s should be quarantined and is not", l))
			labels[l] = true // once per case
		}
	}
	return out
}

// idResolves reports whether an ID of the before-store is kept after the
// cutover: its books row is still there, it is a token of a core key (a step
// imported it into its native keyspace, IDs kept), or a quarantine record
// holds its source row. Set lookups only: the scan built the sets once.
func idResolves(kind, id string, after *storeScan) (kept, quarantined bool) {
	if after.IDs[kind][id] || after.coreTokens[id] {
		return true, false
	}
	return false, after.quarantinedIDs[id]
}

// idProblems: 14 E2, every user, role, key, OAuth identity, import-root and
// run ID of the before-store is kept (or quarantined, with its count in the
// referential check).
func idProblems(before, after *storeScan) []string {
	var out []string
	for _, kind := range sortedKeys(before.IDs) {
		for _, id := range sortedKeys(before.IDs[kind]) {
			if kept, q := idResolves(kind, id, after); !kept && !q {
				out = append(out, fmt.Sprintf("%s ID %s is gone after the cutover", kind, id))
			}
		}
	}
	return out
}

// minRefID is the shortest ID the referential pass matches anywhere in a row
// (a quoted value token, a key segment): ULIDs and UUIDs. Shorter IDs (a seed
// role's name, an import root's integer) would match unrelated text, so they
// count only at the sites that hold them (shortRefFields, wholeValueRef).
const minRefID = 16

// shortRefFields are the JSON fields whose string values are IDs of any
// length: a user's roles and an invite's role.
var shortRefFields = map[string]bool{"role_id": true, "roles": true}

// wholeValueRef reports a key whose whole value is an ID: a secondary index
// (idx:..., e.g. idx:role:name:<name> holds the role's ID) or the import-root
// path index (import_path:path:<path> holds the root's integer ID).
func wholeValueRef(key []byte) bool {
	return bytes.HasPrefix(key, []byte("idx:")) || bytes.HasPrefix(key, []byte("import_path:path:"))
}

// referencedIDs returns the IDs of ids a books row references: a quoted
// string token of its value or a ':' segment of its key (IDs of minRefID or
// more), any string under a shortRefFields field, and the whole value of a
// wholeValueRef key. A row's own ID (the remainder of an idKinds key) is not
// a reference.
func referencedIDs(fam string, key, val []byte, ids map[string]string) []string {
	var out []string
	for i := 0; i < len(val); i++ {
		if val[i] != '"' {
			continue
		}
		j := bytes.IndexByte(val[i+1:], '"')
		if j < 0 {
			break
		}
		if tok := string(val[i+1 : i+1+j]); len(tok) >= minRefID {
			if _, ok := ids[tok]; ok {
				out = append(out, tok)
			}
		}
		i += j + 1
	}
	rest := string(key[len(fam):])
	_, self := idKinds[fam]
	for _, seg := range strings.Split(rest, ":") {
		if len(seg) < minRefID || (self && seg == rest) {
			continue
		}
		if _, ok := ids[seg]; ok {
			out = append(out, seg)
		}
	}
	if wholeValueRef(key) {
		if v := strings.Trim(string(val), `"`); v != "" {
			if _, ok := ids[v]; ok && v != rest {
				out = append(out, v)
			}
		}
	}
	for _, f := range sortedKeys(shortRefFields) {
		if !bytes.Contains(val, []byte(`"`+f+`"`)) {
			continue
		}
		var obj map[string]json.RawMessage
		if json.Unmarshal(val, &obj) != nil {
			continue
		}
		var one string
		var many []string
		switch {
		case json.Unmarshal(obj[f], &one) == nil:
			many = []string{one}
		case json.Unmarshal(obj[f], &many) == nil:
		}
		for _, id := range many {
			if _, ok := ids[id]; ok && len(id) < minRefID {
				out = append(out, id) // a long one was counted as a quoted token
			}
		}
	}
	return out
}

// refProblems: the referential pass (14 E2; 05-storage §5S.3.13), streamed
// over the after-store at dir so it runs at production size too: every ID of
// the before-store a books row of the after-store references
// (referencedIDs) resolves, or names a quarantined row; the latter are
// counted per referencing family and must equal the steps' OrphanedRefs.
func refProblems(t *testing.T, dir string, steps []cutoverStep, before, after *storeScan) []string {
	t.Helper()
	ids := map[string]string{}
	for kind, set := range before.IDs {
		for id := range set {
			ids[id] = kind
		}
	}
	db, err := pebble.Open(dir, &pebble.Options{ReadOnly: true})
	require.NoError(t, err, "open %s read-only", dir)
	defer func() { require.NoError(t, db.Close()) }()
	it, err := db.NewIter(nil)
	require.NoError(t, err)
	defer func() { require.NoError(t, it.Close()) }()
	var out []string
	orphans := map[string]int64{}
	fi := newFamilyIndex()
	for it.First(); it.Valid(); it.Next() {
		fam := fi.family(it.Key())
		if coreFamily(fam) {
			continue
		}
		for _, id := range referencedIDs(fam, it.Key(), it.Value(), ids) {
			kept, q := idResolves(ids[id], id, after)
			switch {
			case kept:
			case q:
				orphans[fam]++
			case len(out) < 50:
				out = append(out, fmt.Sprintf("%s references %s %s, which neither resolves nor is quarantined", it.Key(), ids[id], id))
			}
		}
	}
	reported := map[string]int64{}
	for _, st := range steps {
		for f, n := range st.Report.OrphanedRefs {
			reported[f] += n
		}
	}
	for _, f := range sortedKeys(union(orphans, reported)) {
		if orphans[f] != reported[f] {
			out = append(out, fmt.Sprintf("family %s: %d references to quarantined rows, the steps report %d orphaned_refs", f, orphans[f], reported[f]))
		}
	}
	return out
}

// monotonicBookkeeping are the bookkeeping rows whose value is a number that
// may only grow: the legacy ledger's schema version and the preference ID
// counter each new ledger row bumps.
var monotonicBookkeeping = map[string]func([]byte) (int64, bool){
	"preference:db_version": func(v []byte) (int64, bool) {
		var row struct{ Value string }
		var inner struct{ Version int64 }
		if json.Unmarshal(v, &row) != nil || json.Unmarshal([]byte(row.Value), &inner) != nil || inner.Version == 0 {
			return 0, false
		}
		return inner.Version, true
	},
	"counter:preference": func(v []byte) (int64, bool) {
		n, err := strconv.ParseInt(strings.TrimSpace(string(v)), 10, 64)
		return n, err == nil
	},
}

// bookkeepingProblems: the legacy track's bookkeeping (the golden's
// bookkeeping class, 05-storage §5S.9.1 rows 10 and 16) is grow-only: a boot
// may add ledger rows, but every row there before is still there with the
// same bytes, and the schema version and the counter never go back.
func bookkeepingProblems(before, after *storeScan) []string {
	var out []string
	for _, k := range sortedKeys(before.Bookkeeping) {
		b := before.Bookkeeping[k]
		a, ok := after.Bookkeeping[k]
		switch {
		case !ok:
			out = append(out, fmt.Sprintf("bookkeeping row %s was deleted", k))
		case monotonicBookkeeping[k] != nil:
			bv, okB := monotonicBookkeeping[k](b)
			av, okA := monotonicBookkeeping[k](a)
			switch {
			case !okB || !okA:
				out = append(out, fmt.Sprintf("bookkeeping row %s: cannot read its number (%q, then %q)", k, b, a))
			case av < bv:
				out = append(out, fmt.Sprintf("bookkeeping row %s went back from %d to %d", k, bv, av))
			}
		case !bytes.Equal(a, b):
			out = append(out, fmt.Sprintf("bookkeeping row %s changed: a ledger row is never rewritten", k))
		}
	}
	return out
}

// checkMonotonicListed fails unless every monotonicBookkeeping row is covered
// by a bookkeeping entry of the golden (else its rule never runs).
func checkMonotonicListed(shared []sharedEntry) error {
	for _, k := range sortedKeys(monotonicBookkeeping) {
		if !slices.ContainsFunc(shared, func(e sharedEntry) bool { return e.Class == "bookkeeping" && e.covers([]byte(k)) }) {
			return fmt.Errorf("%s: no bookkeeping entry covers %s", sharedFamiliesGolden, k)
		}
	}
	return nil
}

// upgradeCheckpoint returns the newest checkpoint in now that had lacks: the
// one the upgrade boot took. A store the pre-freeze release wrote already
// holds that release's own checkpoints, taken before it wrote rule 10's rows,
// so only a new one is the pre-migration checkpoint. With none, the problem
// is "" when no step ran (nothing to migrate) and a refusal when one did.
func upgradeCheckpoint(steps int, had, now []string) (cp, problem string) {
	for _, c := range now {
		if !slices.Contains(had, c) && c > cp {
			cp = c
		}
	}
	if cp == "" && steps > 0 {
		problem = fmt.Sprintf("the boot ran %d cutover step(s) and took no pre-migration checkpoint (05-storage §5S.3.12)", steps)
	}
	return cp, problem
}

// byteProblems: 14 E3, every books family outside the steps' Source and the
// list's skipped entries is byte-identical before and after.
func byteProblems(before, after *storeScan) []string {
	var out []string
	for _, f := range sortedKeys(union(digestKeys(before.Families), digestKeys(after.Families))) {
		b, a := before.Families[f], after.Families[f]
		switch {
		case b == nil:
			out = append(out, fmt.Sprintf("family %s: %d keys appeared", f, a.Keys))
		case a == nil:
			out = append(out, fmt.Sprintf("family %s: all %d keys are gone", f, b.Keys))
		case b.Keys != a.Keys || b.digest() != a.digest():
			out = append(out, fmt.Sprintf("family %s changed: %d keys before, %d after%s", f, b.Keys, a.Keys, rowDiff(before, after, f)))
		}
	}
	return out
}

// rowDiff names up to five changed keys of family f when both scans kept rows.
func rowDiff(before, after *storeScan, f string) string {
	if before.rows == nil || after.rows == nil {
		return ""
	}
	fi := newFamilyIndex()
	var diff []string
	for _, k := range sortedKeys(union(before.rows, after.rows)) {
		if fi.family([]byte(k)) != f {
			continue
		}
		if b, ok := before.rows[k]; !ok || !bytes.Equal(b, after.rows[k]) {
			diff = append(diff, fmt.Sprintf("%q", k))
		}
		if len(diff) == 5 {
			break
		}
	}
	return " (e.g. " + strings.Join(diff, ", ") + ")"
}

func digestKeys(m map[string]*familyDigest) map[string]bool {
	out := map[string]bool{}
	for k := range m {
		out[k] = true
	}
	return out
}

func union[V any, W any](a map[string]V, b map[string]W) map[string]bool {
	out := map[string]bool{}
	for k := range a {
		out[k] = true
	}
	for k := range b {
		out[k] = true
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// ---------------------------------------------------------------- one cutover per corpus

// cutoverResult is a corpus' cutover boot, run once per process and shared by
// the three before/after tests: the two scans (with the steps' and the
// list's exclusions, and the "nothing moved" digests when no step is
// registered), the after-copy, the steps and the boot's checkpoint.
type cutoverResult struct {
	steps         []cutoverStep
	shared        []sharedEntry
	before, after *storeScan
	work          string
	checkpoint    string // "" = the boot took none
	// checkpointProblem is upgradeCheckpoint's refusal.
	checkpointProblem string
}

var cutoverRuns struct {
	sync.Mutex
	m    map[string]*cutoverResult
	dirs []string // removed by TestMain (cutoverSuiteCleanup)
}

func runCutover(t *testing.T, c corpus) *cutoverResult {
	t.Helper()
	cutoverRuns.Lock()
	defer cutoverRuns.Unlock()
	if r := cutoverRuns.m[c.name]; r != nil {
		return r
	}
	steps := registeredCutoverSteps(t)
	shared := loadSharedFamilies(t)
	pristine := copyCorpus(t, c)
	// Shared by the tests that use this result, so not under one test's
	// TempDir (removed when that test ends).
	work, err := os.MkdirTemp("", "r2-cutover-"+c.name+"-")
	require.NoError(t, err)
	cutoverRuns.dirs = append(cutoverRuns.dirs, work)
	require.NoError(t, copyCorpusTo(c, work))
	had := checkpoints(t, work)
	cutoverBoot(t, work)
	small := c.name != "shaped"
	spec := scanSpec{steps: steps, shared: shared, keepRows: small, plain: len(steps) == 0}
	cp, problem := upgradeCheckpoint(len(steps), had, checkpoints(t, work))
	r := &cutoverResult{
		steps: steps, shared: shared, work: work,
		before: scanStore(t, storeDB(pristine), spec), after: scanStore(t, storeDB(work), spec),
		checkpoint: cp, checkpointProblem: problem,
	}
	if cutoverRuns.m == nil {
		cutoverRuns.m = map[string]*cutoverResult{}
	}
	cutoverRuns.m[c.name] = r
	return r
}

// requireNoProblems fails with every problem, one per line.
func requireNoProblems(t *testing.T, what string, problems []string) {
	t.Helper()
	if len(problems) > 0 {
		t.Errorf("%s: %d problem(s):\n  %s", what, len(problems), strings.Join(problems, "\n  "))
	}
}

