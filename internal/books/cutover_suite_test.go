// The R2 cutover suite (F2-15; 09 §9.4 R2 "Verification", 05-storage
// §5S.3.13 "Tests", 14 E1-E3): the cross-flip checks every R2 PR runs through
// extraction-gates. The harness works for whatever cutover steps the build
// registers: zero at F2, where each test passes with the "nothing moved"
// outcome and logs it; M2/M7/M8 from F3-07; one more step per flip after that.
//
// Every test runs as subtests over the corpora (design rule 10):
//
//	r0                 F2-12's R0-written stage 1 with F2-13's overlay
//	                   (testdata/r2corpus/overlay), F2-12's committed answers
//	prefreeze-written  the same store after the pre-freeze release's binary
//	                   booted it and wrote a user, an API key, a setting change
//	                   and a scan through its API (prefreezeWrittenCorpus);
//	                   skipped without R2_PREFREEZE_BIN, required when
//	                   R2_CUTOVER_STRICT=1 (the r2-cutover-suite job)
//	shaped             F2-14's production-shaped store (R2_SHAPED_STORE), in
//	                   the production-shaped-store job only
//
// The checks are pure functions over two scans of a store (before the
// cutover boot and after it) and return problems instead of failing, so the
// selftest (TestCutoverOnR0Corpus/selftest/) proves each one bites: a local
// fake cutover step that drops a row, changes an ID, touches a byte outside
// its Source or breaks the drill must make the check report it.
//
// "The cutover boot" is app.New on a copy (06 §6.5.1 P0-P4: the checkpoint,
// the DAG with every cutover step, the ledgers) followed by Close, never Run:
// Run hands the store to module code, whose routine writes (activity rows,
// re-queued scans) are not the cutover's. TestCutoverOnR0Corpus also runs the
// booted copy to readiness. Before/after are two copies, so the committed
// corpus is never opened for write (design rule 2).

const (
	// r2PrefreezeBinEnv names the pre-freeze release's binary for this host
	// (scripts/ci/fetch_prefreeze_binary.sh prints it). Name fixed by F2-15's
	// brief.
	r2PrefreezeBinEnv = "R2_PREFREEZE_BIN"
	// r2StrictEnv set to 1 makes every corpus required (strictCutover).
	r2StrictEnv = "R2_CUTOVER_STRICT"
	// r2ShapedStoreEnv is F2-14's production-shaped store (production_shaped_test.go).
	r2ShapedStoreEnv = "R2_SHAPED_STORE"
	// sharedFamiliesGolden is generated by scripts/ci/gen_shared_family_lists.py.
	sharedFamiliesGolden = "testdata/shared_families.golden"
	// r2CorpusLock serialises every use of the writer's fixed work directory
	// (/tmp/r2corpus: the store's paths point inside it) across processes.
	r2CorpusLock = "/tmp/r2corpus.lock"
	// r2SettleTimeout is the recorder's wait for the boot-time runs: the
	// overlay holds a run waiting on its dependencies, which settles only
	// after R0's 5-minute deps sweep (record_r0_answers.py --settle-timeout).
	r2SettleTimeout = "330"
)

// ---------------------------------------------------------------- the lists

// sharedEntry is one line of shared_families.golden.
type sharedEntry struct {
	Class, Kind, Value, Row, Note string
}

func (e sharedEntry) covers(key []byte) bool {
	if e.Kind == "prefix" {
		return bytes.HasPrefix(key, []byte(e.Value))
	}
	return string(key) == e.Value
}

// skipped reports an entry TestCutoverLeavesOtherFamiliesByteIdentical does
// not hash: moved, rewritten in place by a step outside its Source, or the
// legacy track's bookkeeping (checked grow-only instead, bookkeepingProblems).
// keep entries are hashed like any books key.
func (e sharedEntry) skipped() bool { return e.Class != "keep" }

func parseSharedFamilies(text string) ([]sharedEntry, error) {
	var out []sharedEntry
	for n, line := range strings.Split(text, "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 5 {
			return nil, fmt.Errorf("%s:%d: want 5 TAB-separated columns, got %d", sharedFamiliesGolden, n+1, len(f))
		}
		e := sharedEntry{Class: f[0], Kind: f[1], Value: f[2], Row: f[3], Note: f[4]}
		switch {
		case !slices.Contains([]string{"move", "rewrite", "keep", "bookkeeping"}, e.Class):
			return nil, fmt.Errorf("%s:%d: class %q", sharedFamiliesGolden, n+1, e.Class)
		case e.Kind != "prefix" && e.Kind != "exact":
			return nil, fmt.Errorf("%s:%d: kind %q", sharedFamiliesGolden, n+1, e.Kind)
		}
		out = append(out, e)
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no entry", sharedFamiliesGolden)
	}
	return out, nil
}

func loadSharedFamilies(t *testing.T) []sharedEntry {
	t.Helper()
	raw, err := os.ReadFile(sharedFamiliesGolden)
	require.NoError(t, err, "run python3 scripts/ci/gen_shared_family_lists.py --write")
	out, err := parseSharedFamilies(string(raw))
	require.NoError(t, err)
	require.NoError(t, checkMonotonicListed(out))
	return out
}

