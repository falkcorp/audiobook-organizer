func cutoverSuiteCleanup() {
	prefreeze.Lock()
	if prefreeze.root != "" {
		_ = os.RemoveAll(prefreeze.root)
	}
	prefreeze.Unlock()
	cutoverRuns.Lock()
	for _, d := range cutoverRuns.dirs {
		_ = os.RemoveAll(d)
	}
	cutoverRuns.Unlock()
}
