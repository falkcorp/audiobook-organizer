// TestSharedFamilyCensusDump is gen_shared_family_lists.py's key scan, not a
// check: with R2_CENSUS_OUT set it writes every key of every committed corpus
// store, hex-encoded, as {store: [key, ...]} to that file.
func TestSharedFamilyCensusDump(t *testing.T) {
	out := os.Getenv("R2_CENSUS_OUT")
	if out == "" {
		t.Skip("R2_CENSUS_OUT is not set: run python3 scripts/ci/gen_shared_family_lists.py")
	}
	m := loadR2Manifest(t)
	dump := map[string][]string{}
	for store := range m.Stores {
		for k := range r2ReadStore(t, store) {
			dump[store] = append(dump[store], hex.EncodeToString([]byte(k)))
		}
		sort.Strings(dump[store])
	}
	raw, err := json.Marshal(dump)
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(out, raw, 0o600))
}

// TestMain removes what the suite shares across tests (the prefreeze-written
