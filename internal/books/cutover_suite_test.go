// TestCutoverOnR0Corpus (05-storage §5S.3.13 "Tests"; 14 E1): on the R0-written
// corpus with the overlay, every registered step completes (the boot
// succeeds), per-family counts hold, and the quarantine report equals exactly
// the overlay's quarantine cases (09 §9.3). With no step registered, the
// corpus boots and no books family changed except the legacy track's
// bookkeeping. The booted copy then runs to readiness. selftest/ proves the
// checks bite.
func TestCutoverOnR0Corpus(t *testing.T) {
	if testing.Short() {
		t.Skip("boots the composition on the R2 corpus (extraction-gates r2-cutover-suite)")
	}
	forEachCorpus(t, func(t *testing.T, c corpus) {
		r := runCutover(t, c)
		if c.wrote != nil {
			for _, k := range c.wrote.keys() {
				require.Truef(t, r.before.rows[k] != nil, "the pre-freeze binary's row %s is not in the corpus", k)
			}
		}
		if len(r.steps) == 0 {
			t.Log("no cutover step registered: checking that the corpus boots and no family changed")
			requireNoProblems(t, "no family may change without a cutover step", byteProblems(r.before.plainView(), r.after.plainView()))
			require.Empty(t, r.after.Quarantine, "a quarantine record without a cutover step")
		}
		requireNoProblems(t, "the legacy bookkeeping (grow-only)", bookkeepingProblems(r.before, r.after))
		requireNoProblems(t, "per-family counts", countProblems(r.steps, r.before, r.after))
		requireNoProblems(t, "the quarantine report", quarantineProblems(r.steps, c.quarantineCases, r.after.Quarantine))
		t.Logf("%d steps; %d keys before, %d after; checkpoint taken: %q", len(r.steps), r.before.Total, r.after.Total, r.checkpoint)
		require.Empty(t, r.checkpointProblem)
		if c.name != "shaped" {
			bootsToReady(t, c)
		}
	})
	t.Run("selftest", testCutoverSelftest)
}

// bootsToReady runs the build on a fresh copy until /health reports ready.
func bootsToReady(t *testing.T, c corpus) {
	t.Helper()
	work := copyCorpus(t, c)
	edit, opt := cutoverBootConfig(t, work)
	r := runComposedIn(t, filepath.Join(work, "state"), edit, nil, opt, nil)
	deadline := time.Now().Add(2 * time.Minute)
	for {
		ready, err := shapedReady(r.composed)
		require.NoError(t, err)
		if ready {
			break
		}
		require.True(t, time.Now().Before(deadline), "/health never reported ready")
		time.Sleep(50 * time.Millisecond)
	}
	require.NoError(t, r.stop())
}

// TestCutoverPreservesIDsAndReferences (14 E2; 09 §9.2.3 "IDs and
// references"): every user, role, key, import-root and run ID is kept, and
// every reference resolves or names a quarantined ID counted in orphaned_refs.
func TestCutoverPreservesIDsAndReferences(t *testing.T) {
	if testing.Short() {
		t.Skip("boots the composition on the R2 corpus (extraction-gates r2-cutover-suite)")
	}
	forEachCorpus(t, func(t *testing.T, c corpus) {
		r := runCutover(t, c)
		if len(r.steps) == 0 {
			t.Log("no cutover step registered: every ID stays in its books family")
		}
		require.NotEmpty(t, r.before.IDs["user"], "the corpus holds no user")
		requireNoProblems(t, "IDs", idProblems(r.before, r.after))
		requireNoProblems(t, "references", refProblems(t, storeDB(r.work), r.steps, r.before, r.after))
		if c.wrote != nil {
			for kind, id := range map[string]string{"user": c.wrote.User.ID, "key": c.wrote.APIKey.ID, "run": c.wrote.Scan.OpID} {
				kept, q := idResolves(kind, id, r.after)
				require.Truef(t, kept || q, "the pre-freeze binary's %s %s is gone", kind, id)
			}
		}
	})
}

