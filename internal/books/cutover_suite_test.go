// prefreezeWrittenCorpus is rule 10's corpus, built once per test process:
// F2-12's stage 1 with F2-13's overlay, booted by the pre-freeze binary
// (R2_PREFREEZE_BIN, the tag scripts/ci/fetch_prefreeze_binary.sh resolves)
// on a copy, which writes a user, an API key, a setting change through the
// config route and a library scan of an import root under the copy, all
// through its API after re-minting a key on the copy, and is stopped cleanly
// (scripts/r2corpus/write_prefreeze_rows.py). Its answers are recorded on
// first use (prefreezeAnswers). The owners' oracles take its dir and answers.
func prefreezeWrittenCorpus(t *testing.T) corpus {
	t.Helper()
	prefreeze.Lock()
	defer prefreeze.Unlock()
	if prefreeze.c != nil {
		return *prefreeze.c
	}
	bin := os.Getenv(r2PrefreezeBinEnv)
	require.NotEmpty(t, bin, r2PrefreezeBinEnv)
	root, err := os.MkdirTemp("", "r2-prefreeze-")
	require.NoError(t, err)
	prefreeze.root = root // removed by TestMain (cutoverSuiteCleanup)
	base := r0Corpus(t)
	out := filepath.Join(root, "store")
	stdout := runR2Corpus(t, "scripts/r2corpus/write_prefreeze_rows.py",
		"--binary", bin, "--corpus", base.dir, "--out", out)
	var wrote prefreezeRows
	require.NoError(t, json.Unmarshal([]byte(lastLine(stdout)), &wrote), "write_prefreeze_rows.py's report: %s", stdout)
	require.NotEmpty(t, wrote.User.ID, "no user written")
	require.NotEmpty(t, wrote.APIKey.ID, "no API key written")
	require.NotEmpty(t, wrote.Scan.OpID, "no scan run written")
	c := corpus{name: "prefreeze-written", dir: out, quarantineCases: base.quarantineCases, wrote: &wrote}
	prefreeze.c = &c
	return c
}

// prefreezeAnswers records the pre-freeze binary's answers on the
// prefreeze-written corpus with F2-12's recorder, into the temporary root
// (never over the committed answers/), once per process.
func prefreezeAnswers(t *testing.T) string {
	t.Helper()
	c := prefreezeWrittenCorpus(t)
	prefreeze.Lock()
	defer prefreeze.Unlock()
	if prefreeze.answers == "" {
		dir := filepath.Join(prefreeze.root, "answers")
		recordAnswers(t, c.dir, dir)
		prefreeze.answers = dir
	}
	return prefreeze.answers
}

// recordAnswers boots the pre-freeze binary on a copy of store with F2-12's
// recorder and writes its answers to out. A clean start, the bootstrap
// exchange and every recorded request answering are the "it boots" proof.
func recordAnswers(t *testing.T, store, out string) {
	t.Helper()
	// The recorder reads the corpus manifest beside the store directory (its
	// lapse date, the answer list); a copy in a temporary root gets the
	// committed one.
	if m := filepath.Join(filepath.Dir(store), "manifest.json"); !fileExists(m) {
		raw, err := os.ReadFile(filepath.Join(r2RepoRoot(t), filepath.FromSlash(r2corpusDirRel), "manifest.json"))
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(m, raw, 0o600))
	}
	runR2Corpus(t, "scripts/r2corpus/record_r0_answers.py", "--regenerate",
		"--corpus", store, "--binary", os.Getenv(r2PrefreezeBinEnv), "--binary-tag", "prefreeze",
		"--shift-window", "--settle-timeout", r2SettleTimeout, "--out", out)
}

// runR2Corpus runs one of the corpus scripts with a free port, holding the
// cross-process lock on the writer's fixed work directory, and returns its
// stdout. Its stderr is logged on failure.
func runR2Corpus(t *testing.T, script string, args ...string) string {
	t.Helper()
	root := r2RepoRoot(t)
	lock, err := os.OpenFile(r2CorpusLock, os.O_CREATE|os.O_RDWR, 0o600)
	require.NoError(t, err)
	defer lock.Close()
	require.NoError(t, syscall.Flock(int(lock.Fd()), syscall.LOCK_EX))
	defer func() { _ = syscall.Flock(int(lock.Fd()), syscall.LOCK_UN) }()

	cmd := exec.CommandContext(t.Context(), "python3", append([]string{script, "--port", fmt.Sprint(freePort(t))}, args...)...)
	cmd.Dir = root
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	start := time.Now()
	err = cmd.Run()
	t.Logf("%s: %s", script, time.Since(start).Round(time.Second))
	require.NoError(t, err, "%s failed:\n%s\n%s", script, stdout.String(), stderr.String())
	return stdout.String()
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

func freePort(t *testing.T) int {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	defer l.Close()
	return l.Addr().(*net.TCPAddr).Port
}

func lastLine(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	return lines[len(lines)-1]
}

