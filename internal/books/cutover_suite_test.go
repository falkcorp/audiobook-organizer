// classify names the books family of key (the longest registered prefix), ""
// for a core key (c/, m/).
type familyIndex struct{ prefixes []string }

func newFamilyIndex() familyIndex {
	var p []string
	for _, f := range database.KeyFamilies() {
		p = append(p, f.Prefix)
	}
	return familyIndex{prefixes: p}
}

func (fi familyIndex) family(key []byte) string {
	best := ""
	for _, p := range fi.prefixes {
		if len(p) > len(best) && bytes.HasPrefix(key, []byte(p)) {
			best = p
		}
	}
	if best == "" {
		return "(unregistered)"
	}
	return best
}

func coreFamily(f string) bool { return f == "c/" || f == "m/" }

// scanStore reads every key of the Pebble store at dir, read-only.
func scanStore(t *testing.T, dir string, spec scanSpec) *storeScan {
	t.Helper()
	db, err := pebble.Open(dir, &pebble.Options{ReadOnly: true})
	require.NoError(t, err, "open %s read-only", dir)
	defer func() { require.NoError(t, db.Close()) }()
	it, err := db.NewIter(nil)
	require.NoError(t, err)
	defer func() { require.NoError(t, it.Close()) }()
	s := &storeScan{
		Families: map[string]*familyDigest{},
		InSource: map[string]int64{},
		Skipped:  map[string]int64{},
		IDs:      map[string]map[string]bool{},
	}
	if spec.keepRows {
		s.rows = map[string][]byte{}
	}
	fi := newFamilyIndex()
	for it.First(); it.Valid(); it.Next() {
		s.add(fi, spec, it.Key(), it.Value())
	}
	return s
}

func (s *storeScan) add(fi familyIndex, spec scanSpec, key, val []byte) {
	s.Total++
	fam := fi.family(key)
	if s.rows != nil {
		s.rows[string(key)] = slices.Clone(val)
	}
	if coreFamily(fam) {
		s.coreKeys = append(s.coreKeys, slices.Clone(key))
		if bytes.HasPrefix(key, []byte("c/storage")) && bytes.Contains(key, []byte("quarantine")) {
			if q, ok := decodeQuarantine(val); ok {
				s.Quarantine = append(s.Quarantine, q)
			}
		}
		if spec.hashCore {
			s.digestOf(fam).add(key, val)
		}
		return
	}
	if kind, ok := idKinds[fam]; ok {
		if s.IDs[kind] == nil {
			s.IDs[kind] = map[string]bool{}
		}
		s.IDs[kind][string(key[len(fam):])] = true
	}
	for _, st := range spec.steps {
		if st.inSource(key) {
			s.InSource[st.ID]++
			return
		}
	}
	for _, e := range spec.shared {
		if e.skipped() && e.covers(key) {
			s.Skipped[e.Value]++
			return
		}
	}
	s.digestOf(fam).add(key, val)
}

func (s *storeScan) digestOf(fam string) *familyDigest {
	d := s.Families[fam]
	if d == nil {
		d = &familyDigest{}
		s.Families[fam] = d
	}
	return d
}

// decodeQuarantine decodes a quarantine record, with or without storage's
// codec envelope (a tag byte, then a JSON object carrying "v").
func decodeQuarantine(v []byte) (quarantineRecord, bool) {
	if i := bytes.IndexByte(v, '{'); i > 0 && i <= 4 {
		v = v[i:]
	}
	var q quarantineRecord
	if json.Unmarshal(v, &q) != nil || len(q.Key) == 0 || q.Step == "" {
		return q, false
	}
	return q, true
}

// ---------------------------------------------------------------- the checks

// countProblems: per step, 05-storage §5S.3.13 Verify's count rule, checked
// against an independent scan rather than the step's own numbers alone (rule
// 3): the report's read equals the keys the before-scan found in the Source,
// read = imported + quarantined + deleted, every Source range is empty after
// (Residual keys excepted), and the quarantine records naming the step are as
// many as its report says.
func countProblems(steps []cutoverStep, before, after *storeScan) []string {
	var out []string
	for _, st := range steps {
		r := st.Report
		if got := before.InSource[st.ID]; got != r.Read {
			out = append(out, fmt.Sprintf("%s: the report read %d rows, the Source held %d", st.ID, r.Read, got))
		}
		if sum := r.Imported + r.Quarantined + r.Deleted; sum != r.Read {
			out = append(out, fmt.Sprintf("%s: read %d != imported %d + quarantined %d + deleted %d", st.ID, r.Read, r.Imported, r.Quarantined, r.Deleted))
		}
		if left := after.InSource[st.ID]; left != 0 {
			out = append(out, fmt.Sprintf("%s: %d rows are left in its Source", st.ID, left))
		}
		var q int64
		for _, rec := range after.Quarantine {
			if rec.Step == st.ID {
				q++
			}
		}
		if q != r.Quarantined {
			out = append(out, fmt.Sprintf("%s: the report quarantined %d rows, the store holds %d quarantine records", st.ID, r.Quarantined, q))
		}
	}
	return out
}

// quarantineProblems: the quarantine report equals exactly the overlay's
// quarantine cases that fall in a registered step's Source (09 §9.3): every
// record names a key of one of those cases, and every entity row of such a
// case (a key of an idKinds family: a user, a role, a run, ...) has a record
// naming that entity (a run's opv2:op: and opv3:run: rows are one run, so a
// record of either covers it). A case's secondary rows (its idx: entries, a
// run's events) go with their entity and need no record of their own. A
// record no case accounts for is a row quarantined in error.
func quarantineProblems(steps []cutoverStep, cases []r2Stage2Case, recs []quarantineRecord) []string {
	var out []string
	inAnySource := func(k string) bool {
		for _, st := range steps {
			if st.inSource([]byte(k)) {
				return true
			}
		}
		return false
	}
	fi := newFamilyIndex()
	entity := func(k string) (string, bool) {
		fam := fi.family([]byte(k))
		kind, ok := idKinds[fam]
		return kind + " " + k[len(fam):], ok
	}
	owner := map[string]string{}
	want := map[string]string{} // entity -> case label
	for _, c := range cases {
		for _, k := range c.Keys {
			row, _, _ := strings.Cut(k, "#")
			if !inAnySource(row) {
				continue
			}
			owner[row] = c.Label
			if e, ok := entity(row); ok {
				want[e] = c.Label
			}
		}
	}
	got := map[string]bool{}
	labels := map[string]bool{}
	for _, r := range recs {
		label, ok := owner[string(r.Key)]
		if !ok {
			out = append(out, fmt.Sprintf("%s quarantined %q, which is no overlay quarantine case", r.Step, r.Key))
			continue
		}
		labels[label] = true
		if e, ok := entity(string(r.Key)); ok {
			got[e] = true
		}
	}
	for _, e := range sortedKeys(want) {
		if !got[e] {
			out = append(out, fmt.Sprintf("overlay case %s: %s should be quarantined and is not", want[e], e))
		}
	}
	for _, row := range sortedKeys(owner) {
		if l := owner[row]; !labels[l] {
			out = append(out, fmt.Sprintf("overlay case %s should be quarantined and is not", l))
			labels[l] = true // once per case
		}
	}
	return out
}

// idResolves reports whether an ID of the before-store is kept after the
// cutover: its books row is still there, a core key carries it (a step
// imported it into its native keyspace, IDs kept), or a quarantine record
// holds its source row.
func idResolves(kind, id string, after *storeScan) (kept, quarantined bool) {
	if after.IDs[kind][id] {
		return true, false
	}
	for _, k := range after.coreKeys {
		if containsToken(k, id) {
			return true, false
		}
	}
	for _, q := range after.Quarantine {
		if strings.HasSuffix(string(q.Key), ":"+id) {
			return false, true
		}
	}
	return false, false
}

// containsToken reports whether id occurs in k as a whole token: neither
// neighbour is a letter or digit, so a changed ID that keeps the original as
// a prefix or suffix does not count as the original.
func containsToken(k []byte, id string) bool {
	alnum := func(b byte) bool { return b >= '0' && b <= '9' || b >= 'A' && b <= 'Z' || b >= 'a' && b <= 'z' }
	for i := 0; ; {
		j := bytes.Index(k[i:], []byte(id))
		if j < 0 {
			return false
		}
		at, end := i+j, i+j+len(id)
		if (at == 0 || !alnum(k[at-1])) && (end == len(k) || !alnum(k[end])) {
			return true
		}
		i = at + 1
	}
}

// idProblems: 14 E2, every user, role, key, OAuth identity, import-root and
// run ID of the before-store is kept (or quarantined, with its count in the
// referential check).
func idProblems(before, after *storeScan) []string {
	var out []string
	for _, kind := range sortedKeys(before.IDs) {
		for _, id := range sortedKeys(before.IDs[kind]) {
			if kept, q := idResolves(kind, id, after); !kept && !q {
				out = append(out, fmt.Sprintf("%s ID %s is gone after the cutover", kind, id))
			}
		}
	}
	return out
}

// minRefID is the shortest ID the referential pass looks for in row values:
// ULIDs and UUIDs, never a seed role's name or an import root's integer ID,
// which would match unrelated strings (those references are the owners'
// oracles': 05-rbac's allow and deny before = after, 05-library's roots).
const minRefID = 16

// refProblems: the referential pass (14 E2; 05-storage §5S.3.13): every ID a
// books row of the after-store references, as a quoted JSON string, resolves,
// or names a quarantined row; the latter are counted per referencing family
// and must equal the steps' OrphanedRefs.
func refProblems(steps []cutoverStep, before, after *storeScan) []string {
	ids := map[string]string{}
	for kind, set := range before.IDs {
		for id := range set {
			if len(id) >= minRefID {
				ids[id] = kind
			}
		}
	}
	var out []string
	orphans := map[string]int64{}
	fi := newFamilyIndex()
	for _, k := range sortedKeys(after.rows) {
		if coreFamily(fi.family([]byte(k))) {
			continue
		}
		for _, id := range quotedTokens(after.rows[k], ids) {
			kept, q := idResolves(ids[id], id, after)
			switch {
			case kept:
			case q:
				orphans[fi.family([]byte(k))]++
			default:
				out = append(out, fmt.Sprintf("%s references %s %s, which neither resolves nor is quarantined", k, ids[id], id))
			}
		}
	}
	reported := map[string]int64{}
	for _, st := range steps {
		for f, n := range st.Report.OrphanedRefs {
			reported[f] += n
		}
	}
	for _, f := range sortedKeys(union(orphans, reported)) {
		if orphans[f] != reported[f] {
			out = append(out, fmt.Sprintf("family %s: %d references to quarantined rows, the steps report %d orphaned_refs", f, orphans[f], reported[f]))
		}
	}
	return out
}

// quotedTokens returns the IDs of ids that appear in v as a whole quoted
// string ("<id>").
func quotedTokens(v []byte, ids map[string]string) []string {
	var out []string
	for i := 0; i < len(v); i++ {
		if v[i] != '"' {
			continue
		}
		j := bytes.IndexByte(v[i+1:], '"')
		if j < 0 {
			break
		}
		if tok := string(v[i+1 : i+1+j]); len(tok) >= minRefID {
			if _, ok := ids[tok]; ok {
				out = append(out, tok)
			}
		}
		i += j + 1
	}
	return out
}

// byteProblems: 14 E3, every books family outside the steps' Source and the
// list's skipped entries is byte-identical before and after.
func byteProblems(before, after *storeScan) []string {
	var out []string
	for _, f := range sortedKeys(union(digestKeys(before.Families), digestKeys(after.Families))) {
		b, a := before.Families[f], after.Families[f]
		switch {
		case b == nil:
			out = append(out, fmt.Sprintf("family %s: %d keys appeared", f, a.Keys))
		case a == nil:
			out = append(out, fmt.Sprintf("family %s: all %d keys are gone", f, b.Keys))
		case b.Keys != a.Keys || b.digest() != a.digest():
			out = append(out, fmt.Sprintf("family %s changed: %d keys before, %d after%s", f, b.Keys, a.Keys, rowDiff(before, after, f)))
		}
	}
	return out
}

// rowDiff names up to five changed keys of family f when both scans kept rows.
func rowDiff(before, after *storeScan, f string) string {
	if before.rows == nil || after.rows == nil {
		return ""
	}
	fi := newFamilyIndex()
	var diff []string
	for _, k := range sortedKeys(union(before.rows, after.rows)) {
		if fi.family([]byte(k)) != f {
			continue
		}
		if b, ok := before.rows[k]; !ok || !bytes.Equal(b, after.rows[k]) {
			diff = append(diff, fmt.Sprintf("%q", k))
		}
		if len(diff) == 5 {
			break
		}
	}
	return " (e.g. " + strings.Join(diff, ", ") + ")"
}

func digestKeys(m map[string]*familyDigest) map[string]bool {
	out := map[string]bool{}
	for k := range m {
		out[k] = true
	}
	return out
}

func union[V any, W any](a map[string]V, b map[string]W) map[string]bool {
	out := map[string]bool{}
	for k := range a {
		out[k] = true
	}
	for k := range b {
		out[k] = true
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// ---------------------------------------------------------------- one cutover per corpus

// cutoverResult is a corpus' cutover boot, run once per process and shared by
// the three before/after tests: the two scans with the steps' and the list's
// exclusions, the "nothing moved" scans (no exclusion but the bookkeeping),
// the steps and whether the boot took a checkpoint.
type cutoverResult struct {
	steps           []cutoverStep
	shared          []sharedEntry
	before, after   *storeScan
	plainB, plainA  *storeScan
	checkpointTaken bool
}

var cutoverRuns struct {
	sync.Mutex
	m map[string]*cutoverResult
}

func runCutover(t *testing.T, c corpus) *cutoverResult {
	t.Helper()
	cutoverRuns.Lock()
	defer cutoverRuns.Unlock()
	if r := cutoverRuns.m[c.name]; r != nil {
		return r
	}
	steps := registeredCutoverSteps(t)
	shared := loadSharedFamilies(t)
	pristine := copyCorpus(t, c)
	work := copyCorpus(t, c)
	// A store the pre-freeze release wrote already holds that release's own
	// checkpoints: only one the boot adds counts as the pre-migration one.
	had := len(checkpoints(t, work))
	cutoverBoot(t, work)
	small := c.name != "shaped"
	spec := scanSpec{steps: steps, shared: shared, keepRows: small}
	var bookkeeping []sharedEntry
	for _, e := range shared {
		if e.Class == "bookkeeping" {
			bookkeeping = append(bookkeeping, e)
		}
	}
	plain := scanSpec{shared: bookkeeping, keepRows: small}
	r := &cutoverResult{
		steps: steps, shared: shared,
		before: scanStore(t, storeDB(pristine), spec), after: scanStore(t, storeDB(work), spec),
		plainB: scanStore(t, storeDB(pristine), plain), plainA: scanStore(t, storeDB(work), plain),
		checkpointTaken: len(checkpoints(t, work)) > had,
	}
	if cutoverRuns.m == nil {
		cutoverRuns.m = map[string]*cutoverResult{}
	}
	cutoverRuns.m[c.name] = r
	return r
}

// requireNoProblems fails with every problem, one per line.
func requireNoProblems(t *testing.T, what string, problems []string) {
	t.Helper()
	if len(problems) > 0 {
		t.Errorf("%s: %d problem(s):\n  %s", what, len(problems), strings.Join(problems, "\n  "))
	}
}

