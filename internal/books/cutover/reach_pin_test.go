// reachPinHiddenProblems is what the pin-hides-exactly check fails on, as text:
// the oracle judged again over the same principals with the pin emptied must
// show the pinned cells and no others.
func reachPinHiddenProblems(t testing.TB, vd *reachR0Doc, atoms []m3.AtomRow, whos []reachWho, with reachDiffResult) []string {
	t.Helper()
	without, _, err := reachJudgeErrWith(vd, atoms, whos, map[string]string{})
	if err != nil {
		t.Fatal(err)
	}

	was := reachCellSet(with)
	var hidden []string
	for _, c := range without.cells {
		if !was[c.String()] {
			hidden = append(hidden, c.String())
		}
	}
	sort.Strings(hidden)
	want := slices.Clone(reachPinnedCells)
	sort.Strings(want)
	var out []string
	if !slices.Equal(hidden, want) {
		out = append(out, fmt.Sprintf("the pin hides %d cells, the F4-08 obligation lists %d:\n got %q\nwant %q", len(hidden), len(want), hidden, want))
	}
	if len(with.cells) >= len(without.cells) {
		out = append(out, fmt.Sprintf("the pin hides nothing: %d cells with it, %d without", len(with.cells), len(without.cells)))
	}
	return out
}

// Without the pin the oracle shows exactly the cells the F4-08 obligation lists,
// no more and no fewer: the list in seams.d/F4-07.md is generated by the oracle,
// not written from memory, and a route-level change that adds a cell the pin
// also hides cannot slip in under it.
func TestReachHandlerAdminPin_HidesExactlyTheCellsTheObligationLists(t *testing.T) {
	pd, vd := reachLoad(t)
	atoms := idAtoms()
	with, whos := reachCompare(t, pd, vd, atoms, atoms)
	for _, p := range reachPinHiddenProblems(t, vd, atoms, whos, with) {
		t.Error(p)
	}
}
