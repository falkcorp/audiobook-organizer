package mocks

import "github.com/falkcorp/audiobook-organizer/internal/database"

// The generated MockStore is a library that has never had a row retired, like
// the hand-written database.MockStore (database/retired_mock_store.go), so it
// implements database.RetiredBookFileReader as its plain, expectation-driven
// reads: every row it answers is live and nothing is retired. That is what lets
// the database.*IncludingRetired helpers, which resolve the reader and fail
// closed without it, run against it; a test that stubs GetBookFileByPID
// (GetBookFiles, GetAllBookFilesCore, GetBookFileByPath) is answered through the
// include-retired twin with no extra stub.
//
// It lives in its own file because mock_store.go is regenerated by mockery; the
// file name still ends in mock_store.go so the unreachable-function ratchet
// (scripts/deadcode-ratchet.py) exempts it like the rest of the mock's methods.

var _ database.RetiredBookFileReader = (*MockStore)(nil)

// GetBookFilesIncludingRetired is GetBookFiles: nothing is retired.
func (_m *MockStore) GetBookFilesIncludingRetired(bookID string) ([]database.BookFile, error) {
	return _m.GetBookFiles(bookID)
}

// GetRetiredBookFiles returns nothing: nothing is retired.
func (_m *MockStore) GetRetiredBookFiles(string) ([]database.BookFile, error) { return nil, nil }

// GetAllBookFilesCoreIncludingRetired is GetAllBookFilesCore: nothing is retired.
func (_m *MockStore) GetAllBookFilesCoreIncludingRetired() ([]database.BookFileCore, error) {
	return _m.GetAllBookFilesCore()
}

// GetRetiredVersionsFromBook returns nothing: nothing is retired.
func (_m *MockStore) GetRetiredVersionsFromBook(string) ([]database.BookVersion, error) {
	return nil, nil
}

// GetBookFileByPIDIncludingRetired is GetBookFileByPID: nothing is retired.
func (_m *MockStore) GetBookFileByPIDIncludingRetired(itunesPID string) (*database.BookFile, error) {
	return _m.GetBookFileByPID(itunesPID)
}

// GetBookFileByPathIncludingRetired is GetBookFileByPath: nothing is retired.
func (_m *MockStore) GetBookFileByPathIncludingRetired(path string) (*database.BookFile, error) {
	return _m.GetBookFileByPath(path)
}

// HasRetiredVersions is false: no version of this mock was ever retired.
func (_m *MockStore) HasRetiredVersions() (bool, error) { return false, nil }
