// TestLegacyParseGolden pins that the LEGACY identity parse, ClassifyIntro and
// ParseAudiobookIntro, behaves exactly as it did before the clip classifier
// (ParseClip) existed.
//
// Those two functions produce every identity column readers trust:
// TranscribedTitle/Author/Narrator/Translator/CoverArtist, TranscribeStatus, the
// book-level fills, the owner-manual guards, the metadata search query, the
// apply gate. The clip classifier is a separate parser (clip_classify.go) that
// feeds only BookFile.IntroParse, so nothing here may move when it changes.
//
// The golden is NOT produced by the code under test. It was generated by running
// this test's writer against origin/main's transcribe package (58a035cc1; the
// legacy classify.go and parse.go are identical there and at the branch point
// afb37a9e1, before the clip grammar), over:
//   - testdata/intro_corpus.jsonl            (188 curated clips)
//   - testdata/prod_replay.json              (346 stored production transcripts)
//   - testdata/legacy_parse_extra_inputs.json (every string literal, with literal
//     concatenations evaluated, in the grammar, clip, number, reconcile and
//     re-parse test tables, plus the PR #4687 review inputs)
//
// Each golden line is the input's sha256 prefix and a digest of the whole parse
// result (every field of all three positions and ParseAudiobookIntro), so the file
// carries no title, author or narrator.
//
// Each input is classified at three positions (unknown, first of five, fourth
// of five) so Confidence is pinned as well as Kind, Reason and the fields.
// Zero differences are allowed. To regenerate (only ever against a checkout of
// the legacy code, never to accept a change):
//
//	LEGACY_GOLDEN_WRITE=1 go test ./internal/transcribe -run TestLegacyParseGolden
const (
	legacyGoldenPath  = "testdata/legacy_parse_golden.jsonl"
	legacyGoldenWrite = "LEGACY_GOLDEN_WRITE"
)

type legacyClassify struct {
	Kind          string `json:"kind"`
	Reason        string `json:"reason"`
	Confidence    string `json:"confidence"`
	ChapterNumber int    `json:"chapter"`
	Title         string `json:"title"`
	Author        string `json:"author"`
	Translator    string `json:"translator"`
	Narrator      string `json:"narrator"`
	CoverArtist   string `json:"cover_artist"`
}

// legacyGoldenRow is the parse of one input as the full result.
type legacyGoldenRow struct {
	Key      string            `json:"input_sha256_prefix"`
	Classify []legacyClassify  `json:"classify"`
	Parse    legacyParseFields `json:"parse"`
}

// legacyGoldenLine is what the golden file stores per input: the input's key and
// a digest of the whole parse result. The file holds no parsed title, author or
// narrator, so it copies nothing from the real-library corpora its inputs come
// from; a difference is diagnosed by the failing test, which prints the input and
// the current result.
type legacyGoldenLine struct {
	Key    string `json:"input_sha256_prefix"`
	Digest string `json:"output_digest"`
}

func legacyLine(text string) legacyGoldenLine {
	row := legacyRow(text)
	b, _ := json.Marshal(row)
	h := sha256.Sum256(b)
	return legacyGoldenLine{Key: row.Key, Digest: hex.EncodeToString(h[:16])}
}

type legacyParseFields struct {
	Title, Author, Translator, Narrator, CoverArtist string
}

func legacyKey(text string) string {
	h := sha256.Sum256([]byte(text))
	return hex.EncodeToString(h[:8])
}

func legacyRow(text string) legacyGoldenRow {
	row := legacyGoldenRow{Key: legacyKey(text)}
	for _, pos := range []IntroPosition{UnknownPosition, {Ordinal: 0, Total: 5}, {Ordinal: 3, Total: 5}} {
		c := ClassifyIntro(text, pos)
		row.Classify = append(row.Classify, legacyClassify{
			Kind: string(c.Kind), Reason: c.Reason, Confidence: fmt.Sprintf("%.6f", c.Confidence), ChapterNumber: c.ChapterNumber,
			Title: c.Fields.Title, Author: c.Fields.Author, Translator: c.Fields.Translator,
			Narrator: c.Fields.Narrator, CoverArtist: c.Fields.CoverArtist,
		})
	}
	f := ParseAudiobookIntro(text)
	row.Parse = legacyParseFields{f.Title, f.Author, f.Translator, f.Narrator, f.CoverArtist}
	return row
}

// legacyGoldenInputs returns every input text once.
func legacyGoldenInputs(t *testing.T) []string {
	t.Helper()
	seen := map[string]bool{}
	var texts []string
	add := func(s string) {
		if !seen[s] {
			seen[s] = true
			texts = append(texts, s)
		}
	}

	f, err := os.Open("testdata/intro_corpus.jsonl")
	if err != nil {
		t.Fatalf("open corpus: %v", err)
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		var r struct {
			Text string `json:"text"`
		}
		if err := json.Unmarshal([]byte(line), &r); err != nil {
			t.Fatalf("corpus line: %v", err)
		}
		add(r.Text)
	}
	if err := sc.Err(); err != nil {
		t.Fatalf("scan corpus: %v", err)
	}

	for _, path := range []string{"testdata/prod_replay.json"} {
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}
		var rows []struct {
			Text string `json:"text"`
		}
		if err := json.Unmarshal(raw, &rows); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		for _, r := range rows {
			add(r.Text)
		}
	}

	raw, err := os.ReadFile("testdata/legacy_parse_extra_inputs.json")
	if err != nil {
		t.Fatalf("read extra inputs: %v", err)
	}
	var extra []string
	if err := json.Unmarshal(raw, &extra); err != nil {
		t.Fatalf("extra inputs: %v", err)
	}
	for _, s := range extra {
		add(s)
	}
	sort.Slice(texts, func(i, j int) bool { return legacyKey(texts[i]) < legacyKey(texts[j]) })
	return texts
}

func TestLegacyParseGolden(t *testing.T) {
	texts := legacyGoldenInputs(t)

	if os.Getenv(legacyGoldenWrite) != "" {
		out, err := os.Create(legacyGoldenPath)
		if err != nil {
			t.Fatal(err)
		}
		defer out.Close()
		enc := json.NewEncoder(out)
		for _, s := range texts {
			if err := enc.Encode(legacyLine(s)); err != nil {
				t.Fatal(err)
			}
		}
		t.Skipf("wrote %d rows to %s", len(texts), legacyGoldenPath)
	}

	want := map[string]legacyGoldenLine{}
	f, err := os.Open(legacyGoldenPath)
	if err != nil {
		t.Fatalf("open golden: %v", err)
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for sc.Scan() {
		var r legacyGoldenLine
		if err := json.Unmarshal(sc.Bytes(), &r); err != nil {
			t.Fatalf("golden line: %v", err)
		}
		want[r.Key] = r
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if len(want) != len(texts) {
		t.Fatalf("golden has %d rows, inputs have %d: regenerate against the legacy code only if an input was added", len(want), len(texts))
	}
	diffs := 0
	for _, s := range texts {
		got := legacyLine(s)
		w, ok := want[got.Key]
		if !ok {
			t.Errorf("input %q has no golden row", s)
			diffs++
			continue
		}
		if got.Digest != w.Digest {
			diffs++
			if diffs <= 20 {
				cur, _ := json.Marshal(legacyRow(s))
				t.Errorf("legacy parse changed for %q\n now %s", s, cur)
			}
		}
	}
	if diffs > 0 {
		t.Fatalf("%d of %d inputs differ from the legacy golden (zero allowed)", diffs, len(texts))
	}
}
