// The generator (07 §7.8; 05-http-api §7): core's OpenAPI document in, the two
// committed files of src/generated/ out.
//
//   core.ts        openapi-typescript's `paths`, `components` and `operations`
//                  types, which openapi-fetch's client is typed over.
//   operations.ts  one row per operation: method, path, operationId and whether
//                  its `x-mediacore-permission` is `public`. The runtime reads
//                  it to mark a call `skipAuthRedirect` (07 §7.9, FE-7); the
//                  coverage test reads it to prove no operation is missing.
//
// It is a pure function of the document, so `generate:check` and the coverage
// test can regenerate in memory and compare with what is committed. There is no
// fallback generator: a failure here is a CI failure (07 §7.8).

import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

/** The methods an OpenAPI path item can hold an operation under. */
export const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'] as const;

export type HttpMethod = (typeof HTTP_METHODS)[number];

/** One operation of the document, as the generator and the coverage test see it. */
export interface DocOperation {
  method: HttpMethod;
  path: string;
  operationId: string | null;
  public: boolean;
}

/** The generated files, keyed by their path under src/generated/. */
export type GeneratedFiles = Record<'core.ts' | 'operations.ts', string>;

// The generated files carry a fixed header, as the repo's other generated
// TypeScript does (tygo's, opsgen's): it is text of this generator, so
// regenerating never changes it, and it is not bumped by a regeneration.
function header(file: string, guid: string): string {
  return [
    '// Code generated by generator/generate.ts; DO NOT EDIT.',
    `// file: core/web/packages/api-client/src/generated/${file}`,
    '// version: 1.0.0',
    `// guid: ${guid}`,
    '// last-edited: 2026-11-08',
    '//',
    "// Source of truth: core/openapi/core.json, emitted by core/examples/hello's",
    '// `openapi` subcommand. Regenerate with `npm run generate -w @mediacore/api-client`.',
    '',
  ].join('\n');
}

const CORE_TS_GUID = '9b6133d7-19bf-4bb7-8fa3-a51aa7fbcdc5';
const OPERATIONS_TS_GUID = 'cf0de454-2e65-47c4-b176-b33b177dea72';

/** Every operation of the document in path order, then method order, as written. */
export function operationsOf(doc: OpenAPI3): DocOperation[] {
  const ops: DocOperation[] = [];
  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const op = (item as Record<string, unknown> | undefined)?.[method] as
        | { operationId?: string; [key: string]: unknown }
        | undefined;
      if (!op) continue;
      ops.push({
        method,
        path,
        operationId: typeof op.operationId === 'string' ? op.operationId : null,
        public: op['x-mediacore-permission'] === 'public',
      });
    }
  }
  return ops;
}

function operationsFile(ops: DocOperation[]): string {
  const rows = ops.map(
    (o) =>
      `  { method: ${JSON.stringify(o.method)}, path: ${JSON.stringify(o.path)}, ` +
      `operationId: ${JSON.stringify(o.operationId)}, public: ${o.public} },`,
  );
  return [
    header('operations.ts', OPERATIONS_TS_GUID),
    "import type { OperationInfo } from '../operationInfo';",
    '',
    '/** Every operation of core.json. `public` is `x-mediacore-permission: public`. */',
    `export const coreOperations: readonly OperationInfo[] = [${rows.length ? '\n' + rows.join('\n') + '\n' : ''}];`,
    '',
  ].join('\n');
}

/** Generates both files from a parsed OpenAPI 3.1 document. */
export async function generate(doc: OpenAPI3): Promise<GeneratedFiles> {
  const ast = await openapiTS(doc, { alphabetize: true, exportType: true });
  return {
    'core.ts': header('core.ts', CORE_TS_GUID) + '\n' + astToString(ast),
    'operations.ts': operationsFile(operationsOf(doc)),
  };
}
