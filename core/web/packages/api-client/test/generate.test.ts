// The generator on a document that has operations (core.json has none yet): one
// operations row each, `public` from `x-mediacore-permission`, types for every
// operationId, and the same output on every run.

import { describe, expect, it } from 'vitest';
import type { OpenAPI3 } from 'openapi-typescript';
import { generate, operationsOf } from '../generator/generate';
import fixture from './fixtures/batcave.json';

const doc = fixture as unknown as OpenAPI3;

describe('operationsOf', () => {
  it('lists every operation in path then method order, with public from the extension', () => {
    expect(operationsOf(doc)).toEqual([
      { method: 'post', path: '/api/core/v1/batcave/login', operationId: 'loginToBatcave', public: true },
      { method: 'get', path: '/api/core/v1/batcave/gadgets/{gadgetId}', operationId: 'getGadget', public: false },
      { method: 'delete', path: '/api/core/v1/batcave/gadgets/{gadgetId}', operationId: 'scrapGadget', public: false },
      { method: 'get', path: '/api/core/v1/batcave/signal', operationId: null, public: false },
    ]);
  });
});

describe('generate', () => {
  it('writes a row and a type for each operation, and is deterministic', async () => {
    const first = await generate(doc);
    expect(first['operations.ts']).toContain(
      '{ method: "post", path: "/api/core/v1/batcave/login", operationId: "loginToBatcave", public: true },',
    );
    expect(first['operations.ts']).toContain('operationId: null, public: false },');
    for (const id of ['loginToBatcave', 'getGadget', 'scrapGadget']) expect(first['core.ts']).toContain(id);
    expect(first['core.ts']).toContain('"/api/core/v1/batcave/gadgets/{gadgetId}"');
    expect(await generate(doc)).toEqual(first);
  });

  it('starts every file with the fixed generated header', async () => {
    for (const text of Object.values(await generate(doc))) {
      expect(text.startsWith('// Code generated by generator/generate.ts; DO NOT EDIT.\n// file: ')).toBe(true);
    }
  });
});
