// Command permsgen writes web/src/generated/permissions.ts from books' atom
// table (internal/books/atoms.go), so the SPA never types a permission string
// (07 section 7.18, the permission-literal ESLint rule): the canonical scope
// names the identity flip switches the server to come from the same table the
// server's route requirements and the identity cutover read.
//
//	go run ./cmd/permsgen             # regenerate (make generate-permissions)
//	go run ./cmd/permsgen -check      # exit 1 if the committed file is stale (make ci)
//	go run ./cmd/permsgen -out -      # write to stdout
//
// Run it from the repository root. The output is deterministic (table order,
// no timestamps) so -check can byte-compare it.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/falkcorp/audiobook-organizer/internal/books"
)

const defaultOut = "web/src/generated/permissions.ts"

// The generated file's header. Constants, not time.Now(): a timestamp would
// make -check fail the day after every regeneration. Bump genVersion and
// genLastEdited whenever the generated content changes.
const (
	genVersion    = "0.1.0"
	genGUID       = "d023cb64-054a-48a2-8ce4-df976951d055"
	genLastEdited = "2026-11-21"
)

func main() {
	check := flag.Bool("check", false, "exit 1 if the output file differs from what would be generated")
	out := flag.String("out", defaultOut, "path of the generated TypeScript file, or - for stdout")
	flag.Parse()

	want := generate(books.AtomTable())
	switch {
	case *out == "-":
		_, _ = os.Stdout.Write(want)
	case *check:
		got, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(os.Stderr, "permsgen: read %s: %v\n", *out, err)
			os.Exit(1)
		}
		if !bytes.Equal(got, want) {
			fmt.Fprintf(os.Stderr, "permsgen: %s is stale; run `make generate-permissions` and commit the result\n", *out)
			os.Exit(1)
		}
	default:
		if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
			fmt.Fprintf(os.Stderr, "permsgen: %v\n", err)
			os.Exit(1)
		}
		if err := os.WriteFile(*out, want, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "permsgen: write %s: %v\n", *out, err)
			os.Exit(1)
		}
	}
}

// scopes is every native scope the table names, in first-appearance order
// (the spec's row order), without repeats.
func scopes(table []books.Atom) []string {
	var out []string
	for _, a := range table {
		for _, s := range a.Scopes {
			if !slices.Contains(out, string(s)) {
				out = append(out, string(s))
			}
		}
	}
	return out
}

// constName is the object key of a scope: "books:request.approve" is
// REQUEST_APPROVE inside BOOKS_PERMISSIONS, "core:users.manage" USERS_MANAGE
// inside CORE_PERMISSIONS.
func constName(scope string) string {
	_, action, _ := strings.Cut(scope, ":")
	return strings.ToUpper(strings.NewReplacer(".", "_", "-", "_").Replace(action))
}

func generate(table []books.Atom) []byte {
	var b bytes.Buffer
	all := scopes(table)
	var booksScopes, coreScopes []string
	for _, s := range all {
		if strings.HasPrefix(s, "books:") {
			booksScopes = append(booksScopes, s)
		} else {
			coreScopes = append(coreScopes, s)
		}
	}

	fmt.Fprintf(&b, "// Code generated by cmd/permsgen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// file: %s\n// version: %s\n// guid: %s\n// last-edited: %s\n",
		defaultOut, genVersion, genGUID, genLastEdited)
	b.WriteString(`//
// Source of truth: internal/books/atoms.go (AtomTable, 05-rbac section 6.1).
// Regenerate with ` + "`make generate-permissions`" + `; ` + "`make ci`" + ` fails when this file is stale.
//
// The SPA takes every permission and API-key scope from here: the
// permission-literal ESLint rule (web/eslint-rules/permission-literal.mjs) bans
// a string literal in those positions everywhere else.

`)
	writeObject(&b, "BOOKS_PERMISSIONS", "The books module's scopes (books:*).", booksScopes)
	writeObject(&b, "CORE_PERMISSIONS", "The core scopes a HEAD atom maps to (core:*).", coreScopes)
	b.WriteString("export type BooksPermission = (typeof BOOKS_PERMISSIONS)[keyof typeof BOOKS_PERMISSIONS];\n")
	b.WriteString("export type CorePermission = (typeof CORE_PERMISSIONS)[keyof typeof CORE_PERMISSIONS];\n\n")
	b.WriteString("/**\n * Every scope an API key can be limited to, in the atom table's order. The server\n * refuses a scope the key's owner does not hold.\n */\n")
	b.WriteString("export const API_KEY_SCOPES: readonly string[] = [\n")
	for _, s := range all {
		fmt.Fprintf(&b, "  '%s',\n", s)
	}
	b.WriteString("];\n")
	return b.Bytes()
}

func writeObject(b *bytes.Buffer, name, doc string, scopes []string) {
	fmt.Fprintf(b, "/** %s */\nexport const %s = {\n", doc, name)
	for _, s := range scopes {
		fmt.Fprintf(b, "  %s: '%s',\n", constName(s), s)
	}
	b.WriteString("} as const;\n\n")
}
