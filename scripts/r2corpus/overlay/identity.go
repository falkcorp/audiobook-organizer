// writeInviteAllow takes the one path HEAD writes an invite allow-list row
// on: an invite emailed to an address and accepted (CreateInvite,
// MarkInviteEmailSent, ConsumeInvite).
func writeInviteAllow(w *writer, label string) {
	admin := mustUser(w.db, "admin")
	token := "r2corpus-overlay-invite-" + lower(newID())
	email := "alfred@wayne-manor.invalid"
	_, err := w.db.CreateInvite(&database.Invite{
		Token: token, Username: "alfred.pennyworth", Email: email, RoleID: "viewer",
		CreatedByUserID: admin.ID, ExpiresAt: time.Now().Add(10 * 365 * 24 * time.Hour),
	})
	must(err, "create invite")
	_, err = w.db.MarkInviteEmailSent(token, email, time.Now())
	must(err, "mark invite sent")
	algo, hash, err := authpw.New(authpw.Options{}).Hash(overlayPassword)
	must(err, "hash fixture password")
	_, err = w.db.ConsumeInvite(token, algo, hash)
	must(err, "consume invite")
}
