// ── overlay: status edge values (05-authn §11; SEC-11) ─────────────────────

// userStatusEdges are user statuses HEAD's UserIsActive reads (trimmed,
// case-insensitive, empty is active). CreateUser stores the status as given.
var userStatusEdges = []struct{ label, username, status string }{
	{"status-edge-user-padded-active", "selina.kyle", " Active"},
	{"status-edge-user-upper-disabled", "oswald.cobblepot", "DISABLED"},
	{"status-edge-user-empty", "edward.nygma", ""},
	{"status-edge-user-padded-inactive", "pamela.isley", "inactive "},
	{"status-edge-user-unknown", "victor.fries", "suspended"},
}

func writeUserStatusEdge(w *writer, label string) {
	found := false
	for _, e := range userStatusEdges {
		if e.label != label {
			continue
		}
		found = true
		w.createUser(e.username, []string{"viewer"}, e.status)
	}
	if !found {
		must(fmt.Errorf("no table entry for case %s", label), "case table")
	}
}

// keyStatusEdges are API-key statuses. The owner is james.gordon, the
// overlay's holder of the custom every-atom role (role-every-atom, which
// overlayCases writes first); every key is scoped library.view.
var keyStatusEdges = []struct {
	label, name, status string
	revokedAt, noExpiry bool
}{
	{"status-edge-key-padded-active", "edge-padded-active", " Active", false, false},
	{"status-edge-key-upper-inactive", "edge-upper-inactive", "INACTIVE", false, false},
	{"status-edge-key-empty", "edge-empty", "", false, false},
	{"status-edge-key-padded-revoked", "edge-padded-revoked", "Revoked ", false, false},
	{"status-edge-key-active-revoked-at", "edge-active-revoked-at", "active", true, false},
	{"status-edge-key-unknown", "edge-unknown", "paused", false, false},
	{"status-edge-key-no-expiry", "edge-no-expiry", "active", false, true},
}

func writeKeyStatusEdge(w *writer, label string) {
	found := false
	for _, e := range keyStatusEdges {
		if e.label != label {
			continue
		}
		found = true
		k := w.createKey(userFrom("gordon", "role-every-atom"), e.name, []string{"library.view"}, "active")
		k.Status = e.status
		if e.revokedAt {
			at := k.CreatedAt.Add(time.Minute)
			k.RevokedAt = &at
		}
		if e.noExpiry {
			k.ExpiresAt = nil
		}
		w.rewriteKey(k)
	}
	if !found {
		must(fmt.Errorf("no table entry for case %s", label), "case table")
	}
}

