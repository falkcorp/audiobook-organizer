// allAtoms is HEAD's thirteen atoms, in seed order (05-rbac §6.1; the stage-1
// admin role row holds exactly these).
var allAtoms = []string{
	"library.view", "library.edit_metadata", "library.delete", "library.organize",
	"scan.trigger", "integrations.manage", "users.manage", "settings.manage",
	"playlists.create", "collections.manage", "requests.create", "requests.approve",
	"fingerprint.worker",
}

// createUser creates a user through the store's own writer with a fixture
// password hashed by HEAD's one hashing policy, and returns it.
func (w *writer) createUser(username string, roles []string, status string) *database.User {
	algo, hash, err := authpw.New(authpw.Options{}).Hash(overlayPassword)
	must(err, "hash fixture password")
	u, err := w.db.CreateUser(username, "", algo, hash, roles, status)
	must(err, "create user "+username)
	return u
}

// createKey creates an API key through the store's own writer. The raw token
// is generated by HEAD's generator and thrown away: only its hash is stored,
// as at HEAD, and no raw key exists anywhere in the corpus.
func (w *writer) createKey(owner *database.User, name string, scopes []string, status string) *database.APIKey {
	_, hash, err := database.GenerateAPIKeyToken()
	must(err, "generate key token")
	exp := time.Now().Add(365 * 24 * time.Hour) // R0's maximum key life
	k, err := w.db.CreateAPIKey(&database.APIKey{
		UserID: owner.ID, Name: name, TokenHash: hash, Scopes: scopes, Status: status, ExpiresAt: &exp,
	})
	must(err, "create key "+name)
	return k
}

// rewriteKey stores k as given: for a value CreateAPIKey normalises (it turns
// an empty status into "active") or a field no writer sets alone.
func (w *writer) rewriteKey(k *database.APIKey) {
	w.setJSON("apikey:"+k.ID, k)
}

func (w *writer) createRole(name, desc string, atoms []string) *database.Role {
	r, err := w.db.CreateRole(&database.Role{Name: name, Description: desc, Permissions: atoms})
	must(err, "create role "+name)
	return r
}

func lower(s string) string {
	b := []byte(s)
	for i, c := range b {
		if c >= 'A' && c <= 'Z' {
			b[i] = c + 'a' - 'A'
		}
	}
	return string(b)
}

// ── overlay: roles and keys (05-rbac §6.3) ─────────────────────────────────

// roleIDs carries the custom roles from the role cases to the key cases.
var roleIDs = map[string]*database.Role{}

// users carries the overlay's users between cases.
var users = map[string]*database.User{}

// userFrom returns the user case `by` created under name; overlayCases lists
// the role cases before the key cases that use their holders.
func userFrom(name, by string) *database.User {
	u, ok := users[name]
	if !ok {
		must(fmt.Errorf("%s must be written before this case (it creates %s)", by, name), "case order")
	}
	return u
}

func writeRoleEveryAtom(w *writer, label string) {
	r := w.createRole("GCPD Command", "every atom, held by a custom role (not HEAD's admin seed)", allAtoms)
	roleIDs["every"] = r
	u := w.createUser("james.gordon", []string{r.ID}, "active")
	users["gordon"] = u
}

