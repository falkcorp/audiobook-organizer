// rowsPerBatch is one worker task: one Pebble batch of this many rows, so a
// batch stays a few MiB and the workers have no shared state but the database.
const rowsPerBatch = 20000

// Sources of a family's templates, as the report names them.
const (
	sourceStage1  = "stage1"
	sourceOverlay = "overlay"
)

// familyReport is what generate did for one counts family.
type familyReport struct {
	Prefix string `json:"prefix"`
	// TargetKeys is the P1 key count at this run's scale; Keys is what the
	// store holds afterwards. They differ when stage 1 already holds more than
	// the target (its rows are never deleted: they are the cutover cases) or
	// the family was skipped.
	TargetKeys    int64 `json:"target_keys"`
	Stage1Keys    int64 `json:"stage1_keys"`
	GeneratedKeys int64 `json:"generated_keys"`
	Keys          int64 `json:"keys"`
	RawKeyBytes   int64 `json:"raw_key_bytes"`
	RawValueBytes int64 `json:"raw_value_bytes"`
	// TemplateSource is where the rows to clone came from: "stage1", "overlay"
	// or "" for a family with none.
	TemplateSource string `json:"template_source"`
	Templates      int    `json:"templates"`
	// Skipped is why nothing was generated for the family; empty when the
	// family needed nothing (stage 1 already holds the target) or was grown.
	Skipped string `json:"skipped,omitempty"`
	// Notes are deviations from the P1 sizes a reader should see: a value that
	// could not be resized, a key length widened to stay unique.
	Notes []string `json:"notes,omitempty"`
}

type generateReport struct {
	Scale    float64        `json:"scale"`
	Families []familyReport `json:"families"`
	// OtherKeys is the number of stage-1 keys outside every counts family,
	// left as they were.
	OtherKeys int64 `json:"other_keys"`
}

// plan is the work for one family: how many rows to write and their sizes.
type plan struct {
	fam       family
	rep       *familyReport
	templates []template
	n         int64 // rows to generate
	// Key and value lengths: row i (0-based) has length keyBase (+1 for the
	// first keyRem rows), so the generated bytes add up to the target exactly.
	keyBase, keyRem int64
	valBase, valRem int64
	suffixWidth     int // fewest characters of a generated key suffix, "~" included
	// Bytes the writers have written, for the report.
	keyBytes, valBytes atomic.Int64
}

// scaled is the family's counts at scale, with at least one key kept for a
// family that has any.
func scaled(f family, scale float64) (keys, keyBytes, valueBytes int64) {
	if scale == 1 || f.Keys == 0 {
		return f.Keys, f.RawKeyBytes, f.RawValueBytes
	}
	keys = max(1, int64(math.Round(float64(f.Keys)*scale)))
	// Sizes follow the P1 averages, not the scale, so a small run has the
	// same row shapes.
	avgK := float64(f.RawKeyBytes) / float64(f.Keys)
	avgV := float64(f.RawValueBytes) / float64(f.Keys)
	return keys, int64(math.Round(avgK * float64(keys))), int64(math.Round(avgV * float64(keys)))
}

// generate grows the stage-1 store at storePath to the counts at scale.
func generate(storePath, templatesPath string, fams []family, scale float64, workers int) (*generateReport, error) {
	if workers < 1 {
		workers = runtime.NumCPU()
	}
	cl := newClassifier(fams)
	counted := countedSet(fams)
	base, err := scanPebble(storePath, cl, counted, true)
	if err != nil {
		return nil, err
	}
	var overlay *census
	if templatesPath != "" {
		if overlay, err = scanPebble(templatesPath, cl, counted, true); err != nil {
			return nil, err
		}
	}

	rep := &generateReport{Scale: scale, OtherKeys: base.otherKeys}
	// The plans hold pointers to their family's report, so the reports are
	// allocated one by one and copied into the result at the end.
	var (
		reports []*familyReport
		plans   []*plan
	)
	defer func() {
		for _, fr := range reports {
			rep.Families = append(rep.Families, *fr)
		}
	}()
	for _, f := range fams {
		fr := &familyReport{Prefix: f.Prefix, Stage1Keys: base.keys[f.Prefix]}
		fr.TargetKeys, _, _ = scaled(f, scale)
		fr.Keys, fr.RawKeyBytes, fr.RawValueBytes = base.keys[f.Prefix], base.keyBytes[f.Prefix], base.valueBytes[f.Prefix]
		reports = append(reports, fr)
		pl, err := planFamily(f, scale, base, overlay, fr)
		if err != nil {
			return nil, err
		}
		if pl != nil {
			plans = append(plans, pl)
		}
	}
	if len(plans) == 0 {
		return rep, nil
	}

	db, err := pebble.Open(storePath, &pebble.Options{
		MemTableSize:               64 << 20,
		L0CompactionThreshold:      8,
		L0StopWritesThreshold:      64,
		CompactionConcurrencyRange: func() (int, int) { return 1, max(2, runtime.NumCPU()/2) },
	})
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", storePath, err)
	}
	if err := writePlans(db, plans, workers); err != nil {
		_ = db.Close()
		return nil, err
	}
	if err := db.Flush(); err != nil {
		_ = db.Close()
		return nil, err
	}
	if err := db.Close(); err != nil {
		return nil, err
	}
	// The report's totals are the stage-1 figures plus the bytes the writers
	// counted as they wrote; -mode scan is the independent check.
	for _, pl := range plans {
		pl.rep.GeneratedKeys = pl.n
		pl.rep.Keys += pl.n
		pl.rep.RawKeyBytes += pl.keyBytes.Load()
		pl.rep.RawValueBytes += pl.valBytes.Load()
		pl.noteSizeDrift()
	}
	return rep, nil
}

// noteSizeDrift records on the family's report when its final average key or
// value size is more than 10 % off the P1 average: a template value that is not
// JSON with a string to resize is cloned at its own size, not the P1 average.
func (pl *plan) noteSizeDrift() {
	f, fr := pl.fam, pl.rep
	if f.Keys == 0 || fr.Keys == 0 {
		return
	}
	off := func(got, want int64) bool {
		return math.Abs(float64(got-want)) > 0.1*float64(want)+1
	}
	if off(fr.RawKeyBytes/fr.Keys, f.RawKeyBytes/f.Keys) {
		fr.Notes = append(fr.Notes, fmt.Sprintf("average key %d bytes vs P1 %d", fr.RawKeyBytes/fr.Keys, f.RawKeyBytes/f.Keys))
	}
	if off(fr.RawValueBytes/fr.Keys, f.RawValueBytes/f.Keys) {
		fr.Notes = append(fr.Notes, fmt.Sprintf("average value %d bytes vs P1 %d (a template that is not resizable JSON keeps its own size)", fr.RawValueBytes/fr.Keys, f.RawValueBytes/f.Keys))
	}
}

// keyLen is the length of generated key i (prefix included).
func (pl *plan) keyLen(i int64) int {
	l := int(pl.keyBase)
	if i < pl.keyRem {
		l++
	}
	return max(l, len(pl.rep.Prefix)+pl.suffixWidth)
}

// planFamily decides how the family grows; a nil plan means no row is written.
func planFamily(f family, scale float64, base, overlay *census, fr *familyReport) (*plan, error) {
	keys, keyBytes, valueBytes := scaled(f, scale)
	have := base.keys[f.Prefix]
	if keys <= have {
		return nil, nil // stage 1 already holds the target
	}
	n := keys - have
	pl := &plan{fam: f, rep: fr, n: n}

	src, rows := sourceStage1, base.templates[f.Prefix]
	if len(rows) == 0 && overlay != nil {
		src, rows = sourceOverlay, overlay.templates[f.Prefix]
	}
	if len(rows) == 0 {
		fr.Skipped = "no template row in stage 1 or the overlay store"
		return nil, nil
	}
	fr.TemplateSource, fr.Templates = src, len(rows)
	for _, r := range rows {
		pl.templates = append(pl.templates, compileTemplate(f.Prefix, r.key, r.value))
	}

	// Key lengths: the family's key bytes less stage 1's, spread over n rows.
	keyTotal := keyBytes - base.keyBytes[f.Prefix]
	minKey := int64(len(f.Prefix) + 2) // prefix, "~" and one hex digit
	if keyTotal < n*minKey {
		keyTotal = n * (f.RawKeyBytes / max(1, f.Keys))
		fr.Notes = append(fr.Notes, "stage 1's keys use more of the P1 key bytes than the target leaves: generated keys take the P1 average length")
	}
	pl.keyBase, pl.keyRem = keyTotal/n, keyTotal%n
	// The shortest suffix that keeps n generated keys distinct.
	need := 1 + len(strconv.FormatInt(n-1, 16))
	pl.suffixWidth = need
	if pl.keyBase < int64(len(f.Prefix)+need) {
		fr.Notes = append(fr.Notes, fmt.Sprintf("P1 key length %d is too short for %d distinct keys: generated keys are %d bytes", pl.keyBase, n, len(f.Prefix)+need))
	}

	valTotal := valueBytes - base.valueBytes[f.Prefix]
	if valTotal < 0 {
		valTotal = 0
		fr.Notes = append(fr.Notes, "stage 1's values already exceed the P1 value bytes: generated values are empty")
	}
	pl.valBase, pl.valRem = valTotal/n, valTotal%n
	return pl, nil
}

// suffixFor is generated key suffix i: "~", then i in lowercase hex, zero
// padded to width characters in all. '~' appears in no registered key shape, so
// a generated key never collides with a stage-1 key.
func suffixFor(i int64, width int) string {
	h := strconv.FormatInt(i, 16)
	return "~" + strings.Repeat("0", max(0, width-1-len(h))) + h
}

// writePlans writes every plan's rows with a bounded pool of batch writers.
// Each task is a disjoint index range of one family, so no two workers ever
// write the same key (keys are family prefix plus the row's own index).
func writePlans(db *pebble.DB, plans []*plan, workers int) error {
	g, ctx := errgroup.WithContext(context.Background())
	g.SetLimit(workers)
	for _, pl := range plans {
		for from := int64(0); from < pl.n; from += rowsPerBatch {
			to := min(from+rowsPerBatch, pl.n)
			g.Go(func() error {
				if ctx.Err() != nil {
					return ctx.Err()
				}
				return pl.writeRange(db, from, to)
			})
		}
	}
	return g.Wait()
}

// writeRange writes rows [from, to) of the plan in one batch.
func (pl *plan) writeRange(db *pebble.DB, from, to int64) error {
	b := db.NewBatch()
	defer b.Close()
	var key, val []byte
	var keyBytes, valBytes int64
	empty := pl.valBase == 0 && pl.valRem == 0
	for i := from; i < to; i++ {
		sfx := suffixFor(i, pl.keyLen(i)-len(pl.rep.Prefix))
		key = append(append(key[:0], pl.rep.Prefix...), sfx...)
		val = val[:0]
		if !empty {
			want := int(pl.valBase)
			if i < pl.valRem {
				want++
			}
			val = pl.templates[i%int64(len(pl.templates))].build(val, sfx, want)
		}
		if err := b.Set(key, val, nil); err != nil {
			return err
		}
		keyBytes += int64(len(key))
		valBytes += int64(len(val))
	}
	if err := b.Commit(pebble.NoSync); err != nil {
		return err
	}
	pl.keyBytes.Add(keyBytes)
	pl.valBytes.Add(valBytes)
	return nil
}
